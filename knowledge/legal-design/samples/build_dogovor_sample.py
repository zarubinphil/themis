#!/usr/bin/env python3
"""Образец договора со свободным дизайном — второй образец шага 2.

Фактура вымышлена целиком, персональных данных нет.

Договор не идет в суд как процессуальный документ, поэтому здесь применимы
паттерны, запрещенные для иска: двухслойная структура (краткий слой плюс
полный текст), таблица обязательств вместо прозы, чеклист приемки, смена
гарнитуры. Все они собраны штатными средствами .docx и проверены рендером.

Одна вещь взята из отчетов как обязательная страховка: пункт о приоритете
полного текста над кратким слоем. Без него расхождение слоев — прямой
источник спора, а не удобство.
"""
import os
import sys
from pathlib import Path

ROOT = Path("/Users/fil/Проекты/themis")
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))

from docx.shared import Mm, Pt, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH

from scripts.create_docx import DocBuilder
import legal_design_docx as ld

OUT = HERE / "obrazets_dogovor.docx"
IMG = HERE / "_img"
IMG.mkdir(exist_ok=True)


def build():
    b = DocBuilder()
    # Договору зона штампа не нужна — поля выравниваем под чтение, не под суд.
    s = b.doc.sections[0]
    s.top_margin, s.bottom_margin = Mm(20), Mm(20)
    s.left_margin, s.right_margin = Mm(25), Mm(20)

    b.add_title("ДОГОВОР ПОСТАВКИ ОБОРУДОВАНИЯ № 47")
    b.add_header_date("г. Казань, 15.03.2024")

    # ---------------------------------------------- СЛОЙ 1: главное на странице
    b.add_section("Главное на одной странице")
    ld.add_summary_box(b, [
        [("Кто. ", True),
         ("ООО «Ромашка» (Покупатель) покупает, ООО «Василек» (Поставщик) "
          "поставляет.")],
        [("Что. ", True),
         ("Линия розлива по спецификации — Приложение 1, 4 позиции.")],
        [("Сколько. ", True),
         ("6 000 000 рублей, НДС включен. Предоплата 100 процентов.")],
        [("Когда. ", True),
         ("Оплата — до 25.04.2024. Поставка — до 01.09.2024. Монтаж — "
          "15 рабочих дней с даты поставки.")],
        [("Что будет, если нарушить. ", True),
         ("Просрочка поставки — 0,1 процента в день от стоимости "
          "непоставленного, но не более 10 процентов. Просрочка свыше "
          "30 дней — Покупатель вправе отказаться от договора и требовать "
          "возврата всей предоплаты.")],
    ], fill="F2F2F2")

    p = b.add_body([
        ("Краткий слой не заменяет договор. ", True),
        ("Он приведен для быстрого понимания и не является толкованием. "
         "При любом расхождении между кратким слоем и разделами 1-6 "
         "применяются разделы 1-6.", False),
    ])
    p.paragraph_format.space_after = Pt(10)

    ld.add_static_toc(b, [
        ("D1", "1. Предмет"),
        ("D2", "2. Цена и оплата"),
        ("D3", "3. Сроки и порядок поставки"),
        ("D4", "4. Приемка"),
        ("D5", "5. Ответственность"),
        ("D6", "6. Условия, требующие отдельного внимания"),
    ], title="РАЗДЕЛЫ ДОГОВОРА", linked=True)
    b.add_empty()

    # ------------------------------------------------ карта обязательств
    b.add_section("Кто что делает и к какому сроку")
    t = b.add_table(
        ["Сторона", "Обязательство", "Срок", "Последствие нарушения"],
        [
            ["Покупатель", "Оплатить 6 000 000 руб.", "до 25.04.2024",
             "Поставщик вправе приостановить поставку"],
            ["Поставщик", "Передать оборудование", "до 01.09.2024",
             "неустойка 0,1 процента в день, не более 10 процентов"],
            ["Поставщик", "Смонтировать и запустить", "15 р. д. с поставки",
             "неустойка 0,1 процента в день"],
            ["Покупатель", "Подписать акт либо дать мотивированный отказ",
             "5 р. д. с монтажа", "оборудование считается принятым"],
            ["Поставщик", "Устранить недостатки по акту", "10 р. д.",
             "Покупатель вправе устранить сам за счет Поставщика"],
        ],
        widths=[14, 32, 18, 36],
        aligns=["l", "l", "l", "l"],
        font_size=11)
    ld.shade_header_row(t)
    b.add_empty()

    tl = ld.timeline_png(IMG / "dog_timeline.png", [
        ("15.03.2024", "Договор"),
        ("25.04.2024", "Оплата"),
        ("01.09.2024", "Поставка"),
        ("22.09.2024", "Монтаж"),
        ("29.09.2024", "Приемка"),
    ])
    ld.add_picture_centered(b, tl, 16.0, "Схема. Сроки договора")

    # ------------------------------------------------ СЛОЙ 2: полный текст
    d1 = b.add_section("1. Предмет")
    ld.add_bookmark(d1, "D1")
    ld.add_numbered_body(b, "1.1",
        "Поставщик обязуется передать в собственность Покупателя линию "
        "розлива в комплектации согласно спецификации (Приложение 1), "
        "смонтировать ее и ввести в эксплуатацию, а Покупатель обязуется "
        "принять оборудование и оплатить его.")
    ld.add_numbered_body(b, "1.2",
        "Место поставки: 420021, г. Казань, ул. Примерная, д. 1, "
        "производственное помещение Покупателя.")

    d2 = b.add_section("2. Цена и оплата")
    ld.add_bookmark(d2, "D2")
    ld.add_numbered_body(b, "2.1", [
        ("Цена договора составляет ", False), ("6 000 000", True),
        (" (шесть миллионов) рублей 00 копеек, включая НДС. Цена включает "
         "стоимость оборудования, доставки, монтажа и пусконаладки.", False),
    ])
    ld.add_numbered_body(b, "2.2",
        "Покупатель перечисляет предварительную оплату в размере 100 "
        "процентов цены договора в срок до 25.04.2024.")
    ld.add_numbered_body(b, "2.3",
        "Обязательство по оплате считается исполненным с момента списания "
        "денежных средств с расчетного счета Покупателя.")

    d3 = b.add_section("3. Сроки и порядок поставки")
    ld.add_bookmark(d3, "D3")
    ld.add_numbered_body(b, "3.1",
        "Поставщик передает оборудование в срок до 01.09.2024. Досрочная "
        "поставка допускается с письменного согласия Покупателя.")
    ld.add_numbered_body(b, "3.2",
        "Монтаж и пусконаладка выполняются в течение 15 рабочих дней с даты "
        "передачи оборудования.")

    d4 = b.add_section("4. Приемка")
    ld.add_bookmark(d4, "D4")
    ld.add_numbered_body(b, "4.1",
        "Покупатель в течение 5 рабочих дней с даты завершения монтажа "
        "подписывает акт приема-передачи либо направляет мотивированный "
        "отказ с перечнем недостатков.")
    b.add_body("Проверка при приемке:")
    for item in [
        "комплектность по спецификации (Приложение 1);",
        "отсутствие механических повреждений;",
        "наличие паспортов и сертификатов на оборудование;",
        "выход на заявленную производительность в тестовом режиме;",
        "передача эксплуатационной документации на русском языке.",
    ]:
        b.add_bullet(item)
    b.add_body_spaced(
        "Непроведение любой из проверок не лишает Покупателя права заявить "
        "о скрытых недостатках в пределах гарантийного срока.")

    d5 = b.add_section("5. Ответственность")
    ld.add_bookmark(d5, "D5")
    ld.add_numbered_body(b, "5.1", [
        ("За просрочку поставки Поставщик уплачивает неустойку в размере "),
        ("0,1 процента", True),
        (" от стоимости непоставленного оборудования за каждый день "
         "просрочки, но не более ", False), ("10 процентов", True),
        (" цены договора.", False),
    ])
    ld.add_numbered_body(b, "5.2",
        "При просрочке поставки свыше 30 календарных дней Покупатель вправе "
        "отказаться от договора во внесудебном порядке и потребовать "
        "возврата предварительной оплаты в полном объеме в течение "
        "10 рабочих дней с даты получения уведомления об отказе.")

    # --------------------- визуальное выделение обременительных условий
    d6 = b.add_section("6. Условия, требующие отдельного внимания")
    ld.add_bookmark(d6, "D6")
    b.add_body(
        "Условия ниже ограничивают права Покупателя либо возлагают на него "
        "дополнительные обязанности. Стороны подтверждают, что обсудили их "
        "отдельно.")
    ld.add_summary_box(b, [
        [("6.1. Ограничение ответственности. ", True),
         ("Поставщик не возмещает упущенную выгоду Покупателя. Общий предел "
          "ответственности Поставщика — цена договора.")],
        [("6.2. Изменение комплектации. ", True),
         ("Поставщик вправе заменить отдельные узлы на аналогичные по "
          "характеристикам не ниже заявленных, письменно уведомив "
          "Покупателя не позднее чем за 10 рабочих дней до отгрузки.")],
        [("6.3. Подсудность. ", True),
         ("Споры рассматриваются Арбитражным судом Республики Татарстан.")],
    ], fill="EDEDED")

    b.add_empty()
    b.add_section("Подписи сторон")
    st = b.add_table(
        ["ПОСТАВЩИК", "ПОКУПАТЕЛЬ"],
        [["ООО «Василек»\nИНН 1600000002\n420043, г. Казань,\nул. Образцовая, д. 2",
          "ООО «Ромашка»\nИНН 1600000001\n420021, г. Казань,\nул. Примерная, д. 1"],
         ["Директор _____________ / А. А. Сидоров /",
          "Генеральный директор _____________ / И. И. Петров /"]],
        widths=[50, 50], aligns=["l", "l"], font_size=11, borders=False)
    ld.shade_header_row(st, "F2F2F2")

    ld.set_document_font(b, "Arial")
    ld.add_footer_note(b, "Образец. Фактура вымышлена, реквизиты недействительны.")
    b.add_final_empty()
    b.save(str(OUT))
    return OUT


if __name__ == "__main__":
    print(build())
