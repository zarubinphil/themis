def _scale_word(count: int, scale: str, case: str) -> str:
    """Форма разрядного слова по числу и падежу: одна тысяча, две тысячи,
    пять тысяч; в косвенных падежах при 2-4 разрядное слово во множественном."""
    sg, pl = _SCALES[scale]
    last2 = count % 100
    last1 = count % 10
    if case in ("им", "вин"):
        if last2 in range(11, 15):
            return pl["род"]
        if last1 == 1:
            return sg[case]
        if last1 in (2, 3, 4):
            return sg["род"]
        return pl["род"]
    if last2 in range(11, 15) or last1 != 1:
        return pl[case]
    return sg[case]


def _group_words(value: int, gender: str, case: str) -> list[str]:
    """Число 1..999 словами в нужном падеже и роде."""
    words = []
    hundreds, rest = divmod(value, 100)
    if hundreds:
        words.append(_HUNDREDS[hundreds * 100][case])
    if 10 <= rest <= 19:
        words.append(_TEENS[rest][case])
    else:
        tens, ones = divmod(rest, 10)
        if tens:
            words.append(_TENS[tens * 10][case])
        if ones:
            if ones in _ONES_GENDERED:
                words.append(_ONES_GENDERED[ones][gender][case])
            else:
                words.append(_ONES_PLAIN[ones][case])
    return words


def propis(number: int, gender: str = "м", case: str = "им") -> str:
    """Число прописью. gender: м/ж/с (влияет на последнюю группу);
    case: один из CASE_ALIASES."""
    if not isinstance(number, int) or number < 0:
        raise ValueError("ожидается целое число >= 0")
    if number > 999_999_999_999:
        raise ValueError("предел конвертера — 999 999 999 999")
    case = CASE_ALIASES.get(case.lower())
    if case is None:
        raise ValueError(f"неизвестный падеж: {case}")
    gender = {"m": "м", "f": "ж", "n": "с"}.get(gender.lower(), gender)
    if gender not in ("м", "ж", "с"):
        raise ValueError(f"неизвестный род: {gender}")
    if number == 0:
        return _ZERO[case]

    parts: list[str] = []
    milliards, rest = divmod(number, 1_000_000_000)
    millions, rest = divmod(rest, 1_000_000)
    thousands, units = divmod(rest, 1_000)
    for count, scale, g in ((milliards, "миллиард", "м"),
                            (millions, "миллион", "м"),
                            (thousands, "тысяча", "ж")):
        if count:
            parts += _group_words(count, g, case)
            parts.append(_scale_word(count, scale, case))
    if units:
        parts += _group_words(units, gender, case)
    return " ".join(parts)


def selftest() -> int:
    """Обе оси требования: согласование рода и падежа + контрольные числа
    из приёмки этапа 9.8."""
    checks = [
        # Контрольные числа приёмки.
        (propis(1000), "одна тысяча"),
        (propis(2000000), "два миллиона"),
        (propis(21), "двадцать один"),
        (propis(174000), "сто семьдесят четыре тысячи"),
        (propis(1234567),
         "один миллион двести тридцать четыре тысячи пятьсот шестьдесят семь"),
        (propis(300), "триста"),
        # Род.
        (propis(1, gender="ж"), "одна"),
        (propis(1, gender="с"), "одно"),
        (propis(2, gender="ж"), "две"),
        (propis(21, gender="ж"), "двадцать одна"),
        (propis(122, gender="с"), "сто двадцать два"),
        # Падежи.
        (propis(1000, case="род"), "одной тысячи"),
        (propis(2000000, case="род"), "двух миллионов"),
        (propis(5000, case="дат"), "пяти тысячам"),
        (propis(174000, case="пр"), "ста семидесяти четырех тысячах"),
        (propis(300, case="тв"), "тремястами"),
        (propis(21, case="род"), "двадцати одного"),
        (propis(111000, case="род"), "ста одиннадцати тысяч"),
        # Крайние значения.
        (propis(0), "ноль"),
        (propis(1000000000), "один миллиард"),
        (propis(999999999999), "девятьсот девяносто девять миллиардов "
         "девятьсот девяносто девять миллионов девятьсот девяносто девять "
         "тысяч девятьсот девяносто девять"),
    ]
    fails = [f"«{got}» вместо «{want}»" for got, want in checks if got != want]
    # Стоп-оси: мусор не конвертируется.
    for bad in (-1, 10**12):
        try:
            propis(bad)
            fails.append(f"отрицательное/сверх предела {bad} прошло молча")
        except ValueError:
            pass
    if fails:
        for f in fails:
            print(f"SELTEST FAIL: {f}")
        return 1
    print(f"selftest: {len(checks)} контрольных форм (род, падеж, разряды, "
          f"края) — OK")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Число прописью по-русски.")
    ap.add_argument("number", nargs="?", help="целое число (пробелы допустимы)")
    ap.add_argument("--gender", "-g", default="м",
                    help="род последней группы: м/ж/с (по умолчанию м)")
    ap.add_argument("--case", "-c", default="им",
                    help="падеж: именительный/родительный/дательный/"
                         "винительный/творительный/предложный")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return selftest()
    if args.number is None:
        ap.print_help()
        return 1
    raw = args.number.replace(" ", " ").replace(" ", "").replace("_", "")
    if not raw.isdigit():
        print(f"не число: {args.number!r}")
        return 1
    try:
        print(propis(int(raw), gender=args.gender, case=args.case))
    except ValueError as e:
        print(f"ошибка: {e}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
