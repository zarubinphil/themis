_HOMOGLYPH_SOURCE = {
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К", "M": "М",
    "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
    "a": "а", "c": "с", "e": "е", "o": "о", "p": "р", "x": "х", "y": "у",
}
_HOMOGLYPHS = str.maketrans(_HOMOGLYPH_SOURCE)


def normalize_for_detection(text: str) -> str:
    """OCR-нормализация для детекта: исходный текст маскировщика не переписываем."""
    text = unicodedata.normalize("NFKC", text)
    lat = "".join(re.escape(ch) for ch in _HOMOGLYPH_SOURCE)
    text = re.sub(
        rf"(?<=[А-Яа-яЁё])[{lat}]+|[{lat}]+(?=[А-Яа-яЁё])",
        lambda m: m.group(0).translate(_HOMOGLYPHS),
        text,
    )
    text = text.replace("\u00ad", "").replace("\u200b", "")
    return text



def _obihod_ne_familiya(word: str) -> bool:
    """Слово предметной области — не фамилия, в каком бы падеже ни стояло."""
    w = word.lower()
    return w in _COMMON_NOUN_NOT_SURNAME or any(w.startswith(k) for k in _COMMON_NOUN_STEMS)
# Институт/госорган/регион/норма — не фамилия. Стемы покрывают все падежи и
# прилагательные формы («районный» → «район», «областной» → «област»).
_INSTITUTIONAL_RE = re.compile(
    r"(?i:суд\w*|инспекци\w*|прокуратур\w*|управлени\w*|министерств\w*|"
    r"комитет\w*|департамент\w*|администрац\w*|служб\w*|коллеги\w*|"
    r"палат\w*|полици\w*|отдел\w*|округ\w*|район\w*|област\w*|республик\w*|"
    r"кра[йея]\w*|кодекс\w*|закон\w*|постановлени\w*|определени\w*|"
    r"устав\w*|регион\w*|город\w*|федерац\w*)"
)
# Прилагательное-звено цепочки перед институциональным словом («районный»
# перед «суд», «Чувашская» перед «Республика») — свое окончание, но само по
# себе не институциональный термин.
_ADJ_CHAIN_RE = re.compile(
    r"^[а-яё]+(?:ый|ий|ой|ая|яя|ое|ее|ые|ие|ых|их|ому|ему|ым|им|ом|ем|ую|юю)$"
)
# Средний род прилагательного («Исковое», «Голосовое», «Долевое», «Правовое») —
# форма, которой у русских фамилий НЕТ ни в одном падеже: фамилия бывает мужской
# (-ов/-ин/-ский/-ой) или женской (-ова/-ина/-ская/-ая), но не средней. А в
# юридическом обиходе такие слова стоят в начале почти каждой фразы («Исковое
# заявление подано»), и сторож, кричащий на них, будет снят в первый же день —
# после чего не сторожит вовсе. Множественное «-ые/-ых» сюда НЕ входит:
# «у Ивановых» — живая форма фамилии.
_SREDNIY_ROD_RE = re.compile(r"^[А-ЯЁ][а-яё]+(?:ое|ее)$")


def _looks_institutional(tail: str) -> bool:
    """Смотрит на первые три слова ПОСЛЕ совпадения, только вперед. Если
    институциональное слово нашлось внутри цепочки прилагательных — безопасно
    («Московский районный суд»). Любой другой токен (глагол, местоимение,
    запятая) рвет цепочку немедленно: в «Кузнецова обратилась в суд» слово
    «суд» относится к другому обороту фразы и не должно спасать «Кузнецова» —
    иначе любую голую фамилию можно было бы обелить, дописав «суд» через
    два-три слова дальше.

    Стем сверяется с ЦЕЛЫМ токеном (fullmatch), а не подстрокой: `суд\\w*`
    внутри `.search` цеплялся к «гоСУДарственную» и обелял стоящую перед ней
    голую фамилию — пропуск ровно того рода, ради которого рубеж существует.
    Институциональный термин обязан быть отдельным словом, не куском чужого."""
    for tok in re.findall(r"[а-яёА-ЯЁ]+", tail)[:3]:
        if _INSTITUTIONAL_RE.fullmatch(tok):
            return True
        if not _ADJ_CHAIN_RE.match(tok.lower()):
            return False
    return False


def _looks_like_public_judge_initials_before(text: str, start: int) -> bool:
    before = text[max(0, start - 48):start]
    return bool(re.search(
        r"(?:судь[яеию]|судьей|судьей|председательствующ\w*)\s+"
        r"[А-ЯЁ]\.\s?[А-ЯЁ]\.\s*$",
        before,
        re.I,
    ))


def _residual_extra_matches(text: str) -> list[tuple[int, int, str]]:
    """Находки, которые --mask намеренно не трогает (см. блок выше), но
    --residual обязан отловить: голая фамилия без маркера, фамилия третьего
    лица в середине фразы."""
    found = []
    for pat in (SURNAME_MORPHOLOGY_RE, SURNAME_YAN_RE):
        for m in pat.finditer(text):
            word = m.group(0)
            if _obihod_ne_familiya(word) or _obezlichennaya_storona(word):
                continue
            if _looks_institutional(text[m.end():m.end() + 60]):
                continue
            if _looks_like_public_judge_initials_before(text, m.start()):
                continue
            if _PARTICIPLE_RE.search(word):
                continue      # «Взыскано …» — краткое причастие, а не фамилия
            if _SREDNIY_ROD_RE.match(word):
                continue      # «Исковое заявление» — прилагательное среднего рода
            if word.lower() in _COMMON_ADJ_NOT_SURNAME:
                continue      # «Страховой случай» — относительное прилагательное на -овой
            found.append((m.start(), m.end(), "ФИО?"))
    return found


def residual_matches(text: str) -> list[tuple[int, int, str]]:
    """Полный набор находок второго рубежа: категории маскировщика + свободная
    морфология. Общая точка входа для cmd_residual и selftest."""
    text = normalize_for_detection(text)
    return _find_matches(text) + _residual_extra_matches(text)


def cmd_residual(src: str) -> int:
    """Второй рубеж: детектор запускается напрямую на тексте, который --mask
    мог упустить (неизвестная форма) или который вообще не проходил через
    --mask. Решение «отпускать наружу» не должно зависеть от того же прохода,
    что уже мог ошибиться."""
    text = _read(src)
    matches = residual_matches(text)
    if matches:
        cats = sorted({cat for _, _, cat in matches})
        print(f"pii_gate: остаток похож на персональные данные: {', '.join(cats)}",
              file=sys.stderr)
        return 1
    print("pii_gate: остатка не найдено")
    return 0


