#!/usr/bin/env python3
"""pii_gate.py — обезличивание текста перед выходом за периметр дела.

Зачем. Этап 6/7 отправляет фрагменты дела наружу (внешний поиск практики,
LLM-вызов без доступа к материалам дела) — и туда не должны уйти ФИО, ИНН,
ОГРН, номер дела, паспорт, адрес доверителя. Ручная проверка «на глаз» перед
каждым вызовом не масштабируется и рано или поздно пропустит реквизит.

Fail-closed — ядро контракта, не деталь. Если прибор ничего не нашёл и молча
вернул 0, вызывающий код решит, что текст уже чист, и отправит его как есть —
а на деле это чаще значит «регулярка не сработала», чем «в тексте правда нет
персональных данных» (юридический текст почти всегда содержит хотя бы одно
ФИО или реквизит). Поэтому пустая карта = код 1 и файл на выходе НЕ создаётся:
вызывающий обязан заметить отказ, а не проглотить пустой успех. Тот же
принцип и в конкретных регулярках ниже: где есть выбор между «пропустить
сомнительное» и «замаскировать лишнее», выбрана избыточная маскировка —
обезличенный текст без одного слова легче исправить, чем утечку заметить
постфактум.

Токены — не квадратные скобки. Квадратные скобки в файлах дела запрещены
отдельным правилом (их не пишут в российских процессуальных документах и
держит document_guard.py) — здесь тот же символ был бы и не по стилю, и
конфликтовал бы с реальными купюрами «[...]» внутри цитат. Формат токена —
`{{PII:КАТЕГОРИЯ:N}}`: фигурные скобки в юридическом тексте не встречаются,
N — порядковый номер вхождения (не значения — одинаковое ФИО, встреченное
дважды, получает два разных токена), что делает обратную подстановку через
буквальный `str.replace` однозначной без риска зацепить чужой фрагмент.

Разбор регулярками, не NER-моделью: без сети и без зависимостей, детерминирован,
и для строго форматированных юридических реквизитов (ИНН, ОГРН, паспорт, номер
дела) регулярка надёжнее вероятностной модели.

Фамилии доверителей — из реестра дел, не из регулярки. Реестр читается заново
при каждом запуске через scripts/pd_guard.py:client_names() (та же функция,
что держит git-хук pd_guard). Берётся часть имени папки ДО первого дефиса —
это фамилия по соглашению об именовании cases/<фамилия>[-имя]/. Совпадение
регистронезависимое: обезличенный текст не обязан повторять регистр папки.

ИНН/ОГРН голым числом маскируются по ДЛИНЕ (10/12 и 13/15 цифр подряд), а не
по валидности контрольной суммы: verify_inn.py сам существует ради случая
«реальный ИНН испорчен OCR на одну цифру» (прецедент 02.08.2026) — то есть
невалидная контрольная сумма чаще означает «испорченный настоящий реквизит»,
чем «это не реквизит». Требовать валидность здесь означало бы систематически
НЕ маскировать именно повреждённые реквизиты — обратное тому, для чего нужен
verify_inn.py. Функции оттуда используются как есть (не переизобретаются) —
только чтобы пометить в выводе, прошло ли число контрольную сумму; на решение
«маскировать или нет» это не влияет.
"""
import argparse
import json
import re
import sys
from pathlib import Path

SCRIPTS_DIR = Path(__file__).resolve().parent

# Заглавное слово + заглавное слово + заглавное слово-отчество. Отчество как якорь
# отсекает случайные пары заглавных слов в начале предложения («Истец Кузнецова...»
# без отчества дальше не считается ФИО) при этом отчество почти всегда однозначно
# опознаётся суффиксом.
FIO_RE = re.compile(
    r"\b[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+\s+"
    # Отчество по СТЕМУ, не по одной форме: суффикс + до двух букв склонения.
    # «Иванович»/«Ивановича»/«Петровна»/«Петровны» — все падежи, иначе ФИО
    # оппонента/свидетеля в косвенном падеже (а в судебном тексте оно почти
    # всегда косвенное) утекало целиком.
    r"[А-ЯЁ][а-яё]*(?:ович|евич|ьевич|овн|евн|ьевн|иничн)[а-яё]{0,2}\b"
)
# Фамилия + инициалы: «Иванов И.И.» — вторая частая форма в судебных документах.
FIO_INITIALS_RE = re.compile(r"\b[А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.\s?[А-ЯЁ]\.")
# Одна фамилия рядом с ролевым маркером — без отчества и без реестра, самая
# слабая по признаку форма, поэтому ловится только в контексте: «Истец Кузнецова
# обратилась...» без отчества первая редакция контракта пропускала. `(?i:...)`
# держит регистронезависимость ТОЛЬКО у маркера — сама фамилия обязана начинаться
# с заглавной буквы, иначе поймаем случайное существительное после маркера.
ROLE_SURNAME_RE = re.compile(
    # `истц\w*` рядом с `истец`: у «истец» беглая гласная (истЦа/истЦу/истЦом —
    # «е» выпадает), поэтому один стем `истец\w*` ловил только именительный, а
    # косвенные падежи текли. Маркеры даны по стему (заявител\w*, ответчиц\w*,
    # гражданк\w* — женские/косвенные формы). Разделитель `[\s,]+`: «Ответчик,
    # Петров» с запятой встречается не реже пробела.
    r"(?i:истц\w*|истец|ответчик\w*|ответчиц\w*|заявител\w*|гражданин\w*|"
    r"гражданк\w*|взыскать\s+с|в\s+пользу)"
    r"[\s,]+([А-ЯЁ][а-яё]+)\b"
)
# Значение всегда рядом с меткой — это отсекает произвольные 10/12/13-значные
# числа (суммы, счета) от настоящего реквизита; без метки регулярка на голых
# числах утонула бы в ложных находках.
INN_RE = re.compile(r"ИНН[:\s№]{0,5}(\d{10}|\d{12})\b")
OGRN_RE = re.compile(r"ОГРН(?:ИП)?[:\s№]{0,5}(\d{13}|\d{15})\b")
# Без метки: длина — единственный сигнал (см. обоснование в docstring модуля).
# Отрицательный lookbehind/lookahead — граница цифрового блока, не слова: иначе
# «\b» между двумя цифрами (которых не бывает) ничего бы не резал, а без него
# кусок 12-значного номера ловился бы как 10-значный изнутри более длинного блока.
INN_BARE_RE = re.compile(r"(?<!\d)(\d{10}|\d{12})(?!\d)")
OGRN_BARE_RE = re.compile(r"(?<!\d)(\d{13}|\d{15})(?!\d)")
PASSPORT_RE = re.compile(r"[Пп]аспорт[:\s№]{0,5}(\d{4}\s?\d{6})\b")
# Дефисная форма ИЛИ 11 цифр подряд рядом с меткой: СНИЛС часто пишут без
# дефисов, а без метки 11-значное число не трогаем (INN_BARE ловит 10/12).
SNILS_RE = re.compile(r"СНИЛС[:\s№]{0,5}(\d{3}-\d{3}-\d{3}\s?\d{2}|\d{11})")
# +7/8 — обе формы кода страны в ходу у доверителей и в договорах. Разделители
# — пробел/дефис/точка/скобки в любом числе: «8(917)123-45-67» так же ходовая
# форма, как «+7 917 123 45 67». Скобки/точки без \s — телефон не рвётся строкой.
PHONE_RE = re.compile(
    r"(?:\+7|8)[ \t\-.()]*\d{3}[ \t\-.()]*\d{3}[ \t\-.()]*\d{2}[ \t\-.()]*\d{2}\b"
)
EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
# Дата рождения ловится ТОЛЬКО в связке со словом «рождения» рядом — иначе
# регулярка на голом ДД.ММ.ГГГГ съела бы дату Пленума/постановления, которую
# по контракту маскировать нельзя (обезличенный текст потеряет цитату).
BIRTHDATE_RE = re.compile(
    r"(\d{2}\.\d{2}\.\d{4})\s*(?:года\s+рождения|г\.?\s*рождения|рождения)\b"
)
# Номер дела: маркер «№», «N» (латиница — частая опечатка/OCR-форма) ИЛИ само
# слово «дел(о/а/у/е/ом)» плюс форма номера — арбитражная («А65-12345/2026»)
# либо СОЮ («2-1234/2026»). Анкер по «дело» нужен, потому что «рассмотрено дело
# 2-1234/2026» без № встречается сплошь. Год `/ГГГГ` в форме номера не даёт
# анкеру зацепить № постановления Пленума («№ 7» — без «-.../ГГГГ» не совпадёт).
CASE_NO_RE = re.compile(
    r"(?:№|\bN\b|(?i:дел[оауе]м?))\s*([А-ЯA-Z]\d{1,3}-\d{1,6}/\d{4}|\d{1,2}-\d{1,6}/\d{4})"
)
# Адрес не имеет строгого формата — берём весь хвост строки после метки: это
# избыточно (заденет и соседний текст на той же строке), но избыточность здесь
# безопаснее недомаскировки, а обратимость от ширины захвата не зависит.
# Метка — «адрес:»/«Адрес:» (с двоеточием, любой регистр первой буквы) либо
# «по адресу» без двоеточия — обе формы встречаются в материалах дела.
ADDRESS_RE = re.compile(r"(?:[Аа]дрес\s*:|[Пп]о\s+адресу)\s*([^\n]+)")

# Порядок категорий — приоритет при перекрытии совпадений (см. _find_matches).
CATEGORIES_STATIC = (
    ("ФИО", (FIO_RE, FIO_INITIALS_RE, ROLE_SURNAME_RE)),
    ("ИНН", (INN_RE, INN_BARE_RE)),
    ("ОГРН", (OGRN_RE, OGRN_BARE_RE)),
    ("ДЕЛО", (CASE_NO_RE,)),
    ("ПАСПОРТ", (PASSPORT_RE,)),
    ("СНИЛС", (SNILS_RE,)),
    ("ТЕЛЕФОН", (PHONE_RE,)),
    ("ПОЧТА", (EMAIL_RE,)),
    ("ДАТАРОЖД", (BIRTHDATE_RE,)),
    ("АДРЕС", (ADDRESS_RE,)),
)

# Компонент длиной меньше этого порога — почти всегда инициал («rm», «дв»
# внутри «demidov-ab»), не фамилия. Маскировать инициалы бессмысленно:
# они не идентифицируют человека сами по себе и дают ложные срабатывания на
# обычных двух-трёхбуквенных словах.
MIN_SURNAME_LEN = 4


def _client_surname_pattern() -> re.Pattern | None:
    """Фамилии доверителей — с диска, заново при каждом вызове (contract:
    «список берётся с диска»). Берём часть имени папки до первого дефиса —
    так cases/kuznecova-maria/ даёт фамилию «kuznecova», а не «maria»."""
    try:
        if str(SCRIPTS_DIR) not in sys.path:
            sys.path.insert(0, str(SCRIPTS_DIR))
        import pd_guard
        surnames = sorted(
            {n.split("-", 1)[0] for n in pd_guard.client_names()
             if len(n.split("-", 1)[0]) >= MIN_SURNAME_LEN},
            key=len, reverse=True,
        )
    except Exception:
        surnames = []
    if not surnames:
        return None
    body = "|".join(re.escape(s) for s in surnames)
    return re.compile(rf"\b(?:{body})\w*", re.IGNORECASE)


def _categories():
    client_pat = _client_surname_pattern()
    if client_pat is None:
        return CATEGORIES_STATIC
    return CATEGORIES_STATIC + (("ФИО", (client_pat,)),)


def _find_matches(text: str) -> list[tuple[int, int, str]]:
    """Непересекающиеся находки (start, end, категория), отсортированные по тексту.

    Regex с группой маскирует только группу (значение), без вводной метки
    («ИНН» остаётся читаемым, число — нет). При перекрытии дольше совпадение
    выигрывает: так «Дело № А65-.../2026» не разваливается на кусок ФИО-подобной
    находки внутри.
    """
    raw = []
    for cat, patterns in _categories():
        for pat in patterns:
            for m in pat.finditer(text):
                span = m.span(1) if m.lastindex else m.span(0)
                raw.append((span[0], span[1], cat))
    raw.sort(key=lambda t: (t[0], -(t[1] - t[0])))
    claimed: list[tuple[int, int]] = []
    chosen = []
    for start, end, cat in raw:
        if any(start < e and end > s for s, e in claimed):
            continue
        claimed.append((start, end))
        chosen.append((start, end, cat))
    chosen.sort(key=lambda t: t[0])
    return chosen


def mask_text(text: str) -> tuple[str | None, dict[str, str]]:
    """Маскированный текст + обратимая карта. (None, {}) — ничего не найдено."""
    matches = _find_matches(text)
    if not matches:
        return None, {}
    counters: dict[str, int] = {}
    mapping: dict[str, str] = {}
    out = []
    pos = 0
    for start, end, cat in matches:
        out.append(text[pos:start])
        counters[cat] = counters.get(cat, 0) + 1
        token = f"{{{{PII:{cat}:{counters[cat]}}}}}"
        mapping[token] = text[start:end]
        out.append(token)
        pos = end
    out.append(text[pos:])
    return "".join(out), mapping


def unmask_text(text: str, mapping: dict[str, str]) -> str:
    """Буквальная подстановка токен → исходный фрагмент. Токены не пересекаются
    по построению (нумерация по вхождению), порядок замен не важен."""
    for token, original in mapping.items():
        text = text.replace(token, original)
    return text


def _read(path: str) -> str:
    # newline="" — без универсальной трансляции переводов строк, иначе восстановление
    # не будет побайтовым на файле с \r\n. Path.read_text(newline=...) появился
    # только в 3.13 — на боевом 3.11 используем open() напрямую.
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def _write(path: str, text: str) -> None:
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)


def _checksum_notes(mapping: dict[str, str]) -> list[str]:
    """Advisory-заметки о контрольной сумме голых ИНН/ОГРН — на решение
    «маскировать» не влияет (см. docstring модуля), только на текст в stderr."""
    try:
        if str(SCRIPTS_DIR) not in sys.path:
            sys.path.insert(0, str(SCRIPTS_DIR))
        from verify_inn import inn_valid, ogrn_valid
    except Exception:
        return []
    notes = []
    for token, value in mapping.items():
        if not value.isdigit():
            continue
        if ":ИНН:" in token and not inn_valid(value):
            notes.append(f"  {token}: контрольная сумма ИНН не сошлась "
                         "(возможна порча OCR настоящего реквизита) — замаскирован как есть")
        elif ":ОГРН:" in token and not ogrn_valid(value):
            notes.append(f"  {token}: контрольная сумма ОГРН не сошлась "
                         "(возможна порча OCR настоящего реквизита) — замаскирован как есть")
    return notes


def cmd_mask(src: str, out: str, map_path: str) -> int:
    text = _read(src)
    masked, mapping = mask_text(text)
    if masked is None:
        print("pii_gate: реквизитов не найдено — fail-closed, файл не создаётся "
              "(пустая карта чаще значит «регулярка не сработала», чем «текст чист»)",
              file=sys.stderr)
        return 1
    _write(out, masked)
    Path(map_path).write_text(json.dumps(mapping, ensure_ascii=False, indent=2),
                              encoding="utf-8")
    print(f"pii_gate: обезличено находок: {len(mapping)} → {out}")
    for note in _checksum_notes(mapping):
        print(note, file=sys.stderr)
    return 0


def cmd_unmask(src: str, map_path: str, out: str) -> int:
    mapping = json.loads(Path(map_path).read_text(encoding="utf-8"))
    text = _read(src)
    _write(out, unmask_text(text, mapping))
    print(f"pii_gate: восстановлено → {out}")
    return 0


def cmd_residual(src: str) -> int:
    """Второй рубеж: детектор запускается напрямую на тексте, который --mask
    мог упустить (неизвестная форма) или который вообще не проходил через
    --mask. Решение «отпускать наружу» не должно зависеть от того же прохода,
    что уже мог ошибиться."""
    text = _read(src)
    matches = _find_matches(text)
    if matches:
        cats = sorted({cat for _, _, cat in matches})
        print(f"pii_gate: остаток похож на персональные данные: {', '.join(cats)}",
              file=sys.stderr)
        return 1
    print("pii_gate: остатка не найдено")
    return 0


def selftest() -> int:
    original = (
        "Истец Кузнецова Мария Петровна, ИНН 771234567890, обратилась в суд.\n"
        "Дело № А65-12345/2026. Ответчик ООО «Ромашка», ОГРН 1157746123456.\n"
        "Паспорт 9203 456789, адрес: г. Казань, ул. Баумана, д. 5, кв. 12.\n"
    )
    masked, mapping = mask_text(original)
    assert masked is not None and mapping, "боевой текст обязан дать находки"
    for leak in ("Кузнецова", "771234567890", "А65-12345/2026",
                 "1157746123456", "9203 456789", "Баумана"):
        assert leak not in masked, f"утечка в маске: {leak!r}"
    assert unmask_text(masked, mapping) == original, "восстановление не побайтовое"

    clean = "Обзор практики по неустойке. Норм права достаточно.\n"
    masked_clean, mapping_clean = mask_text(clean)
    assert masked_clean is None and not mapping_clean, \
        "чистый текст обязан давать fail-closed (None), а не пустой успех"

    # Пробы, на которых первая редакция потекла — без метки, без отчества,
    # в нестандартной форме.
    probes = (
        ("Истец Кузнецова обратилась в суд.", "Кузнецова"),
        ("Адрес: г. Казань, ул. Баумана, д. 5.", "Баумана"),
        ("проживающий по адресу г. Казань, ул. Баумана, д. 5", "Баумана"),
        ("Реквизиты плательщика: 7712345678 в поручении.", "7712345678"),
        ("по делу N А65-12345/2026 суд решил", "А65-12345/2026"),
        ("Дело № 2-1234/2026 рассмотрено.", "2-1234/2026"),
        ("Контакт доверителя: +7 917 123-45-67.", "917 123-45-67"),
        ("Направить на kuznecova@mail.ru до среды.", "kuznecova@mail.ru"),
        ("СНИЛС 123-456-789 00 приложен.", "123-456-789 00"),
        ("Ответчик Петров, 14.03.1985 года рождения.", "14.03.1985"),
        # Косвенные/бесскобочные формы, на которых вторая редакция ещё текла.
        ("Передать истцу Сидорову документы.", "Сидорову"),
        ("Ответчик, Петров, возражал против иска.", "Петров"),
        ("Заявление Кузнецовой Марии Петровны получено.", "Петровны"),
        ("От гражданина Иванова Ивана Ивановича.", "Ивановича"),
        ("Контакт: 8(917)123-45-67 доверителя.", "917)123-45-67"),
        ("рассмотрено дело 2-1234/2026 по существу.", "2-1234/2026"),
        ("по делу А40-99999/2025 вынесено решение.", "А40-99999/2025"),
        ("СНИЛС 12345678900 приложен к делу.", "12345678900"),
    )
    for text, secret in probes:
        probe_masked, _ = mask_text(text)
        shown = probe_masked if probe_masked is not None else text
        assert secret not in shown, f"утечка на пробе {text!r}: {secret!r}"

    # Обратная сторона: суды, нормы права и Пленумы масштаб не теряют
    for text, keep in (
        ("Московский районный суд г. Казани рассмотрел дело.", "Московский"),
        ("Применению подлежит ст. 333 ГК РФ.", "ст. 333 ГК РФ"),
        ("Пленум ВС РФ от 24.03.2016 № 7, п. 71.", "Пленум ВС РФ"),
    ):
        keep_masked, _ = mask_text(text)
        shown = keep_masked if keep_masked is not None else text
        assert keep in shown, f"лишняя маскировка: {keep!r} затёрт в {text!r}"

    assert _find_matches(original), "--residual обязан находить реквизиты в боевом тексте"
    assert not _find_matches(clean), "--residual обязан молчать на чистом тексте"

    print("selftest: маскирует боевой текст без утечек (включая пробы без метки/"
          "отчества/пунктуации), восстанавливает побайтово, не трогает суды/нормы/"
          "Пленумы, fail-closed на чистом тексте — ок")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Обезличивание текста перед выходом за периметр дела")
    ap.add_argument("--mask", metavar="ВХОД")
    ap.add_argument("--unmask", metavar="ВХОД")
    ap.add_argument("--residual", metavar="ВХОД")
    ap.add_argument("--out", metavar="ВЫХОД")
    ap.add_argument("--map", metavar="КАРТА.json")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()

    if a.selftest:
        return selftest()

    if a.mask:
        if not a.out or not a.map:
            ap.error("--mask требует --out и --map")
        return cmd_mask(a.mask, a.out, a.map)

    if a.unmask:
        if not a.out or not a.map:
            ap.error("--unmask требует --out и --map")
        return cmd_unmask(a.unmask, a.map, a.out)

    if a.residual:
        return cmd_residual(a.residual)

    ap.error("нужен --mask, --unmask, --residual или --selftest")
    return 2


if __name__ == "__main__":
    sys.exit(main())
