def _obezlichennaya_storona(word: str) -> bool:
    """Нарицательное обозначение стороны в обезличенном акте — не фамилия."""
    return word.lower() in _OBEZLICHENNAYA_STORONA


_PII_TOKEN_RE = re.compile(r"\{\{PII:[А-ЯA-Z]+:\d+\}\}")
_FIO_INITIALS_PREFIX_EXCEPTIONS = frozenset((
    "суд", "суда", "суду", "судом", "суде", "судья", "судьи", "судье",
    "судью", "судьей", "судьей", "судей", "коллегия", "коллегии",
    "председательствующий", "председательствующего", "секретарь", "помощник",
))


def _inside_pii_token(tokens: list[tuple[int, int]], start: int, end: int) -> bool:
    return any(start >= s and end <= e for s, e in tokens)


def _fio_initials_prefix_exception(value: str) -> bool:
    first = value.split(None, 1)[0].strip(".,:;()«»\"'").lower()
    return first in _FIO_INITIALS_PREFIX_EXCEPTIONS


def _find_matches(text: str) -> list[tuple[int, int, str]]:
    """Непересекающиеся находки (start, end, категория), отсортированные по тексту.

    Regex с группой маскирует только группу (значение), без вводной метки
    («ИНН» остается читаемым, число — нет). При перекрытии дольше совпадение
    выигрывает: так «Дело № А65-.../2026» не разваливается на кусок ФИО-подобной
    находки внутри.
    """
    raw = []
    pii_tokens = [m.span() for m in _PII_TOKEN_RE.finditer(text)]
    for cat, patterns in _categories():
        for pat in patterns:
            for m in pat.finditer(text):
                span = m.span(1) if m.lastindex else m.span(0)
                if _inside_pii_token(pii_tokens, span[0], span[1]):
                    continue
                # Нарицательное обозначение стороны из обезличенного акта фамилией
                # не является: правка такого слова ломает цитату из практики,
                # ради которой обезличивание и делается (проба круга 5).
                if cat == "ФИО" and _obezlichennaya_storona(text[span[0]:span[1]]):
                    continue
                if cat == "ФИО" and pat is FIO_INITIALS_RE \
                        and _fio_initials_prefix_exception(text[span[0]:span[1]]):
                    continue
                if cat == "ФИО" and _looks_institutional(text[span[1]:span[1] + 60]):
                    continue
                if cat == "ПАСПОРТ" and _looks_like_money(text, span[0], span[1]):
                    continue
                raw.append((span[0], span[1], cat))
    raw.sort(key=lambda t: (t[0], -(t[1] - t[0])))
    claimed: list[tuple[int, int]] = []
    chosen = []
    for start, end, cat in raw:
        if any(start < e and end > s for s, e in claimed):
            continue
        claimed.append((start, end))
        chosen.append((start, end, cat))
    chosen.sort(key=lambda t: t[0])
    return chosen


_MONEY_TAIL_RE = re.compile(r"^\s*(?:руб(?:\.|лей|ля|ль)?|коп\.?|₽)\b", re.I)


def _looks_like_money(text: str, start: int, end: int) -> bool:
    """10 цифр с пробелами бывают паспортом, но с `руб.` это цена иска."""
    chunk = text[start:end]
    if " " not in chunk and " " not in chunk and " " not in chunk:
        return False
    return bool(_MONEY_TAIL_RE.search(text[end:end + 16]))


def mask_text(text: str) -> tuple[str | None, dict[str, str]]:
    """Маскированный текст + обратимая карта. (None, {}) — ничего не найдено."""
    matches = _find_matches(text)
    if not matches:
        return None, {}
    counters: dict[str, int] = {}
    mapping: dict[str, str] = {}
    out = []
    pos = 0
    for start, end, cat in matches:
        out.append(text[pos:start])
        counters[cat] = counters.get(cat, 0) + 1
        token = f"{{{{PII:{cat}:{counters[cat]}}}}}"
        mapping[token] = text[start:end]
        out.append(token)
        pos = end
    out.append(text[pos:])
    return "".join(out), mapping


def unmask_text(text: str, mapping: dict[str, str]) -> str:
    """Буквальная подстановка токен → исходный фрагмент. Токены не пересекаются
    по построению (нумерация по вхождению), порядок замен не важен."""
    for token, original in mapping.items():
        text = text.replace(token, original)
    return text


def _read(path: str) -> str:
    # newline="" — без универсальной трансляции переводов строк, иначе восстановление
    # не будет побайтовым на файле с \r\n. Path.read_text(newline=...) появился
    # только в 3.13 — на боевом 3.11 используем open() напрямую.
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def _write(path: str, text: str) -> None:
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)


def _write_private_json(path: str, data: dict[str, str]) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
    finally:
        Path(path).chmod(0o600)


def _checksum_notes(mapping: dict[str, str]) -> list[str]:
    """Advisory-заметки о контрольной сумме голых ИНН/ОГРН — на решение
    «маскировать» не влияет (см. docstring модуля), только на текст в stderr."""
    try:
        if str(SCRIPTS_DIR) not in sys.path:
            sys.path.insert(0, str(SCRIPTS_DIR))
        from verify_inn import inn_valid, ogrn_valid
    except Exception:
        return []
    notes = []
    for token, value in mapping.items():
        if not value.isdigit():
            continue
        if ":ИНН:" in token and not inn_valid(value):
            notes.append(f"  {token}: контрольная сумма ИНН не сошлась "
                         "(возможна порча OCR настоящего реквизита) — замаскирован как есть")
        elif ":ОГРН:" in token and not ogrn_valid(value):
            notes.append(f"  {token}: контрольная сумма ОГРН не сошлась "
                         "(возможна порча OCR настоящего реквизита) — замаскирован как есть")
    return notes


def cmd_mask(src: str, out: str, map_path: str) -> int:
    text = _read(src)
    masked, mapping = mask_text(text)
    if masked is None:
        print("pii_gate: реквизитов не найдено — fail-closed, файл не создается "
              "(пустая карта чаще значит «регулярка не сработала», чем «текст чист»)",
              file=sys.stderr)
        return 1
    _write(out, masked)
    _write_private_json(map_path, mapping)
    print(f"pii_gate: обезличено находок: {len(mapping)} → {out}")
    for note in _checksum_notes(mapping):
        print(note, file=sys.stderr)
    return 0


def cmd_unmask(src: str, map_path: str, out: str) -> int:
    mapping = json.loads(Path(map_path).read_text(encoding="utf-8"))
    text = _read(src)
    _write(out, unmask_text(text, mapping))
    print(f"pii_gate: восстановлено → {out}")
    return 0


# ── Второй рубеж (--residual): свободная фамильная морфология ──────────────
# _find_matches/_categories выше — это то, что --mask умеет ПЕРЕПИСАТЬ, и он
# обязан оставаться консервативным: тронуть голую фамилию без маркера
# («Кузнецова обратилась...») означало бы резать обычные предложения там,
# где нет уверенности, что это вообще ФИО. --residual ничего не переписывает,
# он только запрещает отправку — поэтому вправе быть грубее: ловит ЛЮБОЕ
# заглавное слово с фамильным суффиксом без ролевого маркера и без реквизита,
# кроме слов рядом с институциональным контекстом (суд, госорган, регион,
# норма/постановление). Цена ложной тревоги здесь дешевая («проверь
# глазами»), цена пропуска — утечка, поэтому асимметрия в пользу ловли.
# Краткое причастие с корнем на «ск» («Взыскано», «Разыскано») проходит по той же
# форме, что фамилия, и открывает судебную фразу чаще любой фамилии. Второй рубеж,
# кричащий на слове «Взыскано», выключат в первый день, а выключенный не сторожит.
# Фамилий на «-ано/-ено/-яно» в русском практически нет — исключение узкое.
# Краткая форма среднего рода: «Взыскано», «Отказано» — причастие, «Готово»,
# «Основано» — краткое прилагательное. Все они подходят под морфологию фамилии
# (стем на -ов/-ев плюс окончание), а стоят в каждом втором статусе и вердикте
# («Готово к подаче»). Фамилии на -ово в природе есть (Хитрово, Дурново), но они
# наперечет, а второй рубеж не единственный: настоящих доверителей ловит реестр
# дел, а не морфология.
_PARTICIPLE_RE = re.compile(r"(?:ано|ено|яно|ово|ево)$")

# Суффикс фамилии стоит В КОНЦЕ слова и несет падежное окончание, а не любой хвост:
# «Иванов/Иванова/Ивановым», «Маяковский/Маяковская». Прежний класс
# `(?:ов|ев|ин|ск)[а-яё]{0,3}` держал суффикс где угодно внутри слова, поэтому
# кричал на «Договор» (ов+ор), «Переписка» (ск+а) — обиход, стоящий в каждом
# втором предложении (проба 20.08.2026). Теперь -ов/-ев/-ин/-ын требуют падежного
# окончания, а -ск — прилагательного (ский/ская/ского…): «Договор» и «Переписка»
# больше не фамилии, а «Кузнецова», «Ивановых», «Маяковской» ловятся как прежде.
SURNAME_MORPHOLOGY_RE = re.compile(
    r"\b[А-ЯЁ][а-яё]+"
    r"(?:(?:ов|ев|ев|ин|ын)(?:а|у|е|ым|ом|ой|ы|ых|ыми)?"
    r"|ск(?:ий|ого|ому|им|ом|ая|ой|ую|ие|их|ими))\b"
)
SURNAME_YAN_RE = re.compile(r"\b[А-ЯЁ][а-яё]+ян(?:а|у|е|ом|ы|ов|ам|ами|ах)?\b")
# -овой/-евой у прилагательного («Страховой случай», «Правовой вопрос») и у
# родительного фамилии («у Ивановой») морфологически неотличимы. Настоящих
# доверителей ловит реестр дел, а не морфология (см. комментарий модуля), поэтому
