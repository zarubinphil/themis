// Врезка Метиды в дом Фемиды. Тонкая прослойка, а не второй компрессор.
//
// СОСТОЯНИЕ: прослойка врезана в двух точках scripts/markdown_extract.py - в обеих ветках, где
// дом отдает модели тело, а не превью. Обе зовут один фасад scripts/themis_metiz.py с одним
// профилем; врезки и откат выписаны построчно в его же docstring, второй копии тут не заводим.
//
// Почему именно эти две ветки. markdown_extract.py - роутер извлечения текста, и по умолчанию он
// отдает модели только превью на 800 символов. Тело уходит ровно двумя путями:
//   --inline - документ дела ЦЕЛИКОМ, с потолком --max-chars 200000 символов;
//   --grep   - список совпадений, и потолка символов у него НЕТ НИ ОДНОГО: 400 в срезе hits[:400]
//              считает ЭЛЕМЕНТЫ списка, а не символы.
// Раньше здесь стояло "ветка --grep отдает до 400 строк и порога сжатия не берет" - это была
// гипотеза без замера, и замер ее опроверг. По 260 материалам дел из кеша дома боевым шаблоном
// читателей: медиана выдачи --grep 1872 байта, p90 27 213, максимум 694 243 байта. То есть один
// настоящий документ (обвинительное заключение на 1,15 МБ) уже сегодня отдает через --grep в 3,5
// раза больше, чем пропустила бы защищенная ветка --inline, и делал это мимо прибора.
//
// Выигрыш на этих же 260 материалах сегодня НУЛЕВОЙ, и причина названа честно [замер]: обратимые
// свертки Метиды ищут повтор, а номер строки, приклеенный к каждой строке выдачи, делает все
// строки разными. Те же 216 совпадений самого крупного документа без номеров жмутся
// 692 727 -> 209 168 байт (69,8%), с номерами - 0,0%. Значит врезка в --grep стоит СТРАХОВКОЙ,
// а не экономией: вход возвращается байт в байт (доктрина 4), но ветка без потолка символов
// больше не проходит мимо прибора и мимо журнала замеров.
//
// ФОРМАТ СТРОКИ ВЫДАЧИ РЕШЕНО НЕ МЕНЯТЬ, и это решение замерено, а не выбрано вкусом. Соблазн
// очевиден: приклеить к строке имя файла, чтобы выдача стала обычной формой grep и попала под
// свертку общего префикса. [замер] по 376 материалам кеша дома, тот же боевой шаблон: формат с
// префиксом дает 3 382 602 байта против нынешних 3 253 572, то есть ХУЖЕ НА 129 030 байт, и
// сжатие все равно не срабатывает - номер строки остается и оставляет строки уникальными.
// Медиана растет с 2277 до 2498 байт, p90 с 21 708 до 22 711. Плата берется с КАЖДОГО вызова,
// а выигрыша нет ни на одном. Переоткрывать вопрос только с новым замером.
//
// Почему прослойка, а не прямой вызов. Дом Фемиды - питон, ядро Метиды - TypeScript. Мост через
// node неизбежен, и он стоит здесь один раз, а не в каждом приборе дома. Второго компрессора в
// доме не заводится: вся логика сжатия живет в Метиде, тут только перевод формы и три вещи,
// которых у Метиды нет и быть не должно: дело Фемиды, журнал Фемиды, откат Фемиды.
//
// ПРОФИЛЬ - ТОЛЬКО audit, и overrides не подаются НИ ОДНОГО (решение владельца). У audit
// allowLossy: false, targetRatio: 1, evidenceMinConfidence: 0.45. Последнее число не косметика:
// юридический маркер (срок, госпошлина, статья, определение) метится уверенностью 0.65, и при
// пороге 0.7 прибор считал бы такую строку уликой и тут же разрешал ее потерять.
// resolveProfile сам краснеет на попытке ослабить audit - это проба (в) самопроверки.
//
// ДОКТРИНА 2 - ДВА СЛУЧАЯ, И ЗДЕСЬ ЖИВУТ ОБА.
//   Обратимая свертка (нормальный и, под audit, единственный случай): на диск НЕ ложится
//   НИЧЕГО. В тексте остается [metiz:fold ... expand] с абсолютной командой разворота. Проверено
//   живым прогоном: 104.2 КБ образца свернулись до 42.3 КБ и развернулись командой expand байт в
//   байт. Копия документа клиента на диске тут была бы платой байтами за ноль информации, и для
//   юридического дома это не только байты: материалы дела - адвокатская тайна, и лишний их
//   экземпляр вне дерева cases/ уходит мимо дисциплины хранения дел и мимо описи доказательств.
//   Вынос содержимого в хранилище: ОТВЕРГАЕТСЯ ЦЕЛИКОМ. Под audit его быть не может по
//   построению (allowLossy: false снимает необратимый шаг), поэтому ccr-результат тут - не
//   рабочий случай, а нарушение контракта конвейера, и ответ на нарушение fail-closed: оригинал
//   на диск не ложится, сжатое не выдается, наружу уходит вход байт в байт. Доктрина 2 держится
//   сама собой: выход не изменен - восстанавливать нечего.
//   Причина отказа, а не непрозрачного ключа в маркере: маркер выноса нес `дело
//   cases/<клиент>/<дело>` и команду restore --case, а маркер ложится в ТЕКСТ, который читает
//   модель. Имя доверителя - персональные данные, и уходить за границу процесса им нельзя.
//   Непрозрачный ключ убрал бы имя из текста, но потребовал бы указателя «ключ -> дело» на диске:
//   нового постоянного места, где имя доверителя лежит вне дерева cases, со своим сроком жизни и
//   своей уборкой. В юридическом доме это второй экземпляр адвокатской тайны мимо описи, и
//   платить им за ветку, которой быть не должно, - плохая сделка.
//
// ИЗОЛЯЦИЯ ПАМЯТИ - причина, по которой ветка выноса написана именно так, а не голым openCcr().
// Хранилище обратимости Метиды общее на все дома, и openCcr() сложил бы оригинал документа
// клиента А туда, откуда его достанет прогон по делу клиента Б. Механизм изоляции у Метиды УЖЕ
// ЕСТЬ и написан ровно под это требование - metiz/src/state/ccr/shared.ts, функция
// openSharedStore(projectId): каждый projectId получает СВОЙ каталог CCR, и own() каталога
// одного дела физически не видит файлы другого (metiz/src/state/ccr.ts:176). Второй такой
// механизм здесь не сочиняется - используется этот. projectId дома Фемиды устроен как
// "themis:cases/<клиент>/<дело>".
//
// Отсюда fail-closed В ДАННЫХ: дело из пути не вывелось - НЕ СЖИМАЕМ ВОВСЕ. Дело нужно и для
// каталога хранилища, и для замера в журнале; без него единственный оставшийся вариант - общий
// каталог на всех клиентов, то есть ровно та дыра, ради которой все это написано. Цена решения
// названа вслух: материал из инбокса, еще не разложенный по делу, не сжимается. Молчаливая
// врезка без изоляции хуже отсутствующей врезки.
//
// Fail-open В ТРАФИКЕ (доктрина 5) держится на ИМПОРТЕ, а не только внутри вызова: дома Метиды
// нет - импорт не бросает, дом Фемиды работает как работал, без сжатия, и говорит об этом вслух
// в поле note. Урок взят из дома Гелиоза: там прошлая версия бросала на импорте и роняла
// install.sh у стороннего пользователя на первой же команде.
//
// Доктрина 3 (нет замера - нет цифры): каждый проход пишет строку в журнал дома, включая проход
// с выключенным сжатием. Своего журнала замеров у Фемиды нет (token_ledger.py читает чужие
// session-jsonl Claude Code, а audit.log - человекочитаемая лента брифингов), поэтому журнал
// заведен по образцу Гелиоза: $THEMIS_HOME/state/squeeze.jsonl, каталог 0700, файл 0600.
//
// I7: Authorization не разбирается, не хранится, не логируется - заголовков этот слой не видит
// вовсе. В журнал не попадает ни текста, ни имени клиента, ни пути дела: дело представлено
// slot-меткой, метка вызова обрезана до класса [a-z0-9_-] длиной до 32.
//
// Слот считается HMAC-SHA256 на секретном ключе дома, а не голым sha256 строки дела, и это
// правка по находке аудитора, а не вкус. Несоленый хеш был ПСЕВДОНИМОМ, а не безличным
// идентификатором: словарь возможных входов лежит у владельца прямо на диске (cases/*). [замер]
// по живому дому: 80 дел дерева cases, таблица «слот -> дело» строится за 0,1 мс, и по ней 32 из
// 33 разных слотов накопленного журнала (241 запись) назвались настоящим делом за 0,9 мс от нуля.
// Ключ лежит вне кода и вне git по канону дома; устройство и цена - у slotOf ниже.
//
// Импорт .ts из .mjs работает без сборки: Node 24 стрипает типы на лету, отдельного шага сборки
// у дома не появляется.

