// КАНОНИЧЕСКИЙ корень дерева дел. Якорь - расположение самого слоя: он всегда лежит в
// {корень проекта}/scripts/. Тот же якорь и по той же причине, что у сторожа дома
// (scripts/claude_guard.py, PROJECT_ROOT): «сторож судит материалы НАШИХ дел, а не любой путь со
// словом cases: чужой репозиторий под /tmp/chuzhoy/cases и /tmp/cases - не наши дела». Урок там
// записан пробой 20.08.2026, и здесь он повторился слово в слово.
//
// realpath снимает симлинки с ОБЕИХ сторон сравнения: иначе симлинк, положенный внутрь дерева
// дел, вводил бы под видом дела что угодно снаружи.
//
// Корня нет на диске (свежий клон без дел) - CASES_ROOT равен null, и делом не признается ничто.
// Это fail-closed в данных: без корня дерева сверять не с чем, а значит и сжимать нельзя.
const CASES_ROOT = (() => {
  try { return realpathSync(path.resolve(path.dirname(realpathSync(SELF)), '..', 'cases')) }
  catch { return null }
})()

// NFC обязателен: macOS отдает пути в NFD, и то же имя в двух нормализациях сравнилось бы как два
// разных. Ниже это же NFC уходит в projectSlot, который хеширует СТРОКУ, - без него оригинал не
// нашелся бы под собственным делом.
const segments = (s) => s.split(path.sep).filter(Boolean).map(x => x.normalize('NFC'))

/**
 * Дело из пути к файлу: cases/<клиент>/<дело>, и ТОЛЬКО если файл действительно лежит под
 * каноническим корнем дерева дел.
 *
 * Раньше делом признавался любой путь, где нашелся сегмент «cases» (parts.lastIndexOf('cases')).
 * Живой прогон: /tmp/cases/podstavnoy-klient/delo-2026/obrazec.json прошел как настоящее дело,
 * получил право на сжатие, свой каталог хранилища и строку в журнале замеров. То есть fail-closed
 * по делу снимался подставным путем, а вместе с ним снималась и изоляция памяти: под чужой слот
 * можно было завести что угодно.
 *
 * Путь не существует на диске - дела нет (realpath отказывает). Прибор дома подает сюда
 * os.path.abspath от файла, который он только что прочитал, так что существование - не догадка.
 */
export function caseFromPath(p) {
  if (typeof p !== 'string' || p.length === 0 || !CASES_ROOT) return null
  let real
  try { real = realpathSync(path.resolve(p)) } catch { return null }
  const a = segments(real)
  const root = segments(CASES_ROOT)
  // Нужны и клиент, и дело: "cases/ivanov" - это клиент целиком, а не одно его дело.
  if (a.length < root.length + 2) return null
  for (let i = 0; i < root.length; i++) {
    // Регистр не сверяем: APFS и HFS+ его не различают, и один каталог приходил бы то своим, то
    // чужим в зависимости от того, как его набрали. Так же судит сторож дома (_match_cases_root).
    if (a[i].toLowerCase() !== root[i].toLowerCase()) return null
  }
  return ['cases', a[root.length], a[root.length + 1]].join('/').normalize('NFC')
}

/** Ключ изоляции. Дом назван в ключе, чтобы дело Фемиды не схлопнулось с одноименным чужим. */
const projectId = (caseId) => 'themis:' + caseId

/** Хранилище ЭТОГО дела и только его. Общего каталога на всех клиентов не существует. */
const storeFor = (caseId) => openSharedStore(projectId(caseId))

/**
 * Положить оригинал в хранилище СВОЕГО дела. Единственная дверь к диску в этом файле, и она
 * ведет только в каталог названного дела - другой двери у слоя нет.
 *
 * Сжатие эту дверь не открывает: вынос под audit отвергается, и оригинал на диск не ложится.
 * Дверь остается по двум причинам. Первая: ею проверяется изоляция памяти - проба (д) кладет
 * оригинал под дело A и спрашивает его из-под дела B. Вторая: она парная к restoreText, а без
 * пары восстановление нечем было бы проверить. Появится профиль с законным выносом - вход сюда
 * уже написан и уже изолирован.
 */
export async function stash(caseId, text) {
  if (!openSharedStore) throw new Error(`метида: хранилище недоступно - ${offReason}`)
  const c = String(caseId ?? '').normalize('NFC')
  if (!c) throw new Error('метида: не названо дело, класть оригинал некуда')
  return storeFor(c).put(String(text), { home: METIZ })
}

/** Метка вызова - метка ШАГА конвейера, не текста. Чужое сюда не пролезет: режем по классу. */
function safeLabel(label) {
  const s = String(label ?? '').toLowerCase().replace(/[^a-z0-9_-]/g, '')
  return s ? s.slice(0, 32) : null
}

/**
 * Каталог, закрытый от ЧУЖИХ. Снимаются ТОЛЬКО биты группы и прочих, биты ВЛАДЕЛЬЦА не трогаются.
 *
 * Устройство взято у Метиды дословно (metiz/src/state/ccr.ts, ensurePrivateDir) и по той же
 * причине. Раньше тут стоял chmod(dir, 0o700), и это ровно та ошибка, которая в проекте уже
 * записана уроком: каталог, намеренно закрытый владельцем на 500, получал обратно право записи -
 * прибор безопасности сам ослаблял защиту. Живой прогон подтвердил: dr-x------ до прогона,
 * drwx------ после. I7 требует закрыть доступ чужим, а не навязать владельцу свой набор прав.
 */
function ensurePrivateDir(dir) {
  mkdirSync(dir, { recursive: true, mode: 0o700 })
  const mode = statSync(dir).mode & 0o777
  if ((mode & 0o077) === 0) return
  chmodSync(dir, mode & 0o700)
  const после = statSync(dir).mode & 0o777
  if ((после & 0o077) !== 0) throw new Error(`каталог ${dir} остался с режимом ${после.toString(8)}`)
}

/**
 * КЛЮЧ СЛОТА. Слот дела обязан держать сразу два свойства, и несоленый sha256 держал только одно.
 *
 * Свойство первое, СТАБИЛЬНОСТЬ: одно дело обязано давать один и тот же слот из прогона в прогон,
 * иначе журнал замеров перестанет сходиться сам с собой, а отказ восстановления перестанет
 * сходиться с журналом. Случайная метка на прогон это свойство ломает и потому не годится.
 *
 * Свойство второе, БЕЗЛИЧНОСТЬ, и вот его-то и не было. Слот считался как 16 hex от sha256 СТРОКИ
 * дела, без секрета, а строка дела - это `cases/<клиент>/<дело>`, то есть словарь возможных
 * входов лежит у владельца прямо на диске. [замер] на живом доме: 80 дел дерева cases, таблица
 * «слот -> дело» строится за 0,1 мс, и по ней 32 из 33 разных слотов накопленного журнала
 * назвались настоящим делом за 0,9 мс от нуля. Значит и журнал замеров, и текст отказа
 * восстановления деанонимизировались словарем за секунды - слот был псевдонимом доверителя.
 *
 * HMAC с секретным ключом держит оба свойства сразу: тот же ключ даст тот же слот, а без ключа
 * предпосчитать таблицу «слот -> дело» не по чему.
 *
 * Ключ НЕ в коде и НЕ в git (канон дома): отдельный файл в закрытом каталоге секретов владельца,
 * рядом с прочими секретами дома. Точный путь тут НЕ НАЗВАН намеренно: репозиторий публичный, а
 * машинный путь к секрету, единожды опубликованный, остается в форках и зеркалах после удаления -
 * это ловит сторож персональных данных дома (scripts/pd_guard.py, публикационная гигиена).
 * Собирается он в коде ниже из домашнего каталога, родится при первом обращении, читается при
 * старте процесса. Путь подменяем
 * переменной окружения - тем же швом, что и THEMIS_HOME, и ровно для того же: чтобы проба считала
 * слоты на СВОЕМ ключе и не трогала ключ живых дел.
 */
const SLOT_KEY_DEFAULT = path.join(homedir(), '.secrets', 'themis-metiz-slot.key')
const SLOT_KEY_FILE = process.env.THEMIS_SLOT_KEY_FILE || SLOT_KEY_DEFAULT

/** Имя схемы в записи журнала. Стоит полем, чтобы шов между старыми и новыми слотами был виден
 *  машинно, а не угадывался по дате: старые записи этого поля не несут вовсе. */
const SLOT_SCHEME = 'hmac-v2'

/**
 * Прочитать ключ, а нет его - породить.
 *
 * Рождение идет режимом 'wx', и это не украшение: два параллельных прогона дома иначе затерли бы
 * ключ друг друга, и слоты ОДНОГО дела разошлись бы посреди журнала. 'wx' отдает EEXIST
 * проигравшему, тот просто читает уже готовый ключ.
 *
 * Права ставятся СНЯТИЕМ чужих битов, а не chmod 700 - та же дисциплина, что у каталога и файла
 * журнала выше, и по той же причине: прибор безопасности не вправе возвращать права, которые
 * владелец снял сам. На секрете эта ошибка стоила бы дороже, чем на журнале.
 */
function loadSlotKey() {
  try {
    ensurePrivateDir(path.dirname(SLOT_KEY_FILE))
    try {
      const fd = openSync(SLOT_KEY_FILE, 'wx', 0o600)
      try { writeSync(fd, randomBytes(32).toString('hex') + '\n') } finally { closeSync(fd) }
    } catch (e) {
      if (!e || e.code !== 'EEXIST') throw e
    }
    const fd = openSync(SLOT_KEY_FILE, 'r')
    let raw
    try {
      const mode = fstatSync(fd).mode & 0o777
      if (mode & 0o077) fchmodSync(fd, mode & 0o700)
      raw = readFileSync(fd, 'utf8').trim()
    } finally { closeSync(fd) }
    // Пустой или огрызок ключа не принимаем молча: слот на нем выглядел бы обычным, а перебирался
    // бы почти как раньше. Лучше без слота, чем со слотом-обманкой.
    if (raw.length < 32) throw new Error(`ключ короче 32 символов (${raw.length})`)
    return { key: Buffer.from(raw, 'utf8'), reason: null }
  } catch (e) {
    return { key: null, reason: `ключ слота недоступен: ${e && e.message || e}` }
  }
}

const { key: SLOT_KEY, reason: slotKeyReason } = loadSlotKey()

/**
 * Slot дела для журнала и для отказа восстановления. Считаем сами, а не зовем projectSlot Метиды:
 * без Метиды импорта нет, а запись в журнал обязана лечь и на выключенном сжатии (доктрина 3).
 * Формула здесь СВОЯ и с формулой Метиды намеренно разошлась: у Метиды слот - служебное имя
 * каталога внутри процесса, у Фемиды он ложится в durable-журнал и в текст отказа, и цена
 * перебора тут другая.
 *
 * Ключа нет - слота нет (null). Подставить сюда несоленый хеш «чтобы хоть что-то было» значило бы
 * тихо вернуть ту самую дыру: запись выглядела бы обычной, а раскрывалась бы словарем дел с диска
 * за миллисекунды. Работу дома отсутствие ключа не останавливает (fail-open в трафике): замер все
 * равно ложится, просто безымянным, и причина уезжает вызывающему в note.
 */
const slotOf = (caseId) => SLOT_KEY
  ? createHmac('sha256', SLOT_KEY).update(projectId(caseId), 'utf8').digest('hex').slice(0, 16)
  : null

/** Причины склеиваются, а не вытесняют друг друга: молчать о слепоте прибора нельзя (доктрина 3). */
const notes = (...chasti) => chasti.filter(Boolean).join('; ') || undefined

// Замер не вправе ронять работу (fail-open), но и молчать о собственной слепоте не вправе:
// причина отказа уезжает в note выдачи.
function journal(rec) {
  try {
    ensurePrivateDir(path.dirname(JOURNAL))
    // Права ставятся ДО записи, а не после. При appendFileSync + chmod свежий файл журнала успевал
    // полежать с правами по umask (0644 при типовом umask 022), и в это окно его читал кто угодно.
    // openSync с режимом закрывает окно ПОСТРОЕНИЕМ: файл рождается уже закрытым. 0600 переживает
    // любой типовой umask - маскируются только те биты, которых в 0600 нет.
    const fd = openSync(JOURNAL, 'a', 0o600)
    try {
      // Файл мог остаться с прошлого раза с чужими правами. Снимаем ТОЛЬКО чужие биты, владельца
      // не трогаем - тот же довод, что и у каталога.
      const mode = fstatSync(fd).mode & 0o777
      if (mode & 0o077) fchmodSync(fd, mode & 0o700)
      writeSync(fd, JSON.stringify(rec) + '\n')
    } finally {
      closeSync(fd)
    }
    return null
  } catch (e) {
    return `журнал: ${e && e.message || e}`
  }
}

/**
 * Одна строка журнала. Каждое поле проверено глазами на персональные данные:
 *   ts        - время, не ПД
 *   label     - метка шага конвейера, класс [a-z0-9_-]: имени клиента там быть не может
 *   case_slot - 16 hex от HMAC-SHA256 дела на секретном ключе дома; без ключа перебирать нечего.
 *               Прежняя формула (голый sha256 строки дела) это обещание НЕ держала: словарь дел
 *               лежит у владельца на диске, и слот раскрывался им за миллисекунды
 *   slot_scheme - имя схемы слота; шов со старыми записями виден машинно, они этого поля не несут
 *   profile   - всегда audit
 *   kind      - тип содержимого (json, text и прочее), не ПД
 *   before, after, saved_pct, tokens_* - числа
 *   lossy     - под audit всегда false; пишется как доказательство, а не как настройка
 *   ccr       - контентный хеш оригинала; без каталога своего дела ничего не резолвит
 *   engine    - metiz либо null (сжатие выключено)
 * Текста, путей, имен клиентов и номеров дел в записи нет ни одним полем.
 */
function record({ label, slot, before, after, r, id, engine: eng }) {
  return {
    ts: new Date().toISOString(),
    label,
    case_slot: slot,
    slot_scheme: slot ? SLOT_SCHEME : null,
    profile: PROFILE,
    kind: r ? r.kind : null,
    before,
    after,
    saved_pct: before > 0 ? Number((((before - after) / before) * 100).toFixed(1)) : 0,
    tokens_before: r ? r.tokensBefore : null,
    tokens_after: r ? r.tokensAfter : null,
    // Источник числа печатается всегда: у Метиды он бывает и точным, оценка обязана быть названа.
    tokens_estimated: r ? r.tokenSource !== 'exact' : null,
    token_source: r ? r.tokenSource : null,
    lossy: r ? !r.reversible : false,
    evidence_lost: r ? r.evidenceLost : null,
    ccr: id,
    engine: eng,
  }
}

/**
 * Сжать текст под делом. Возвращает { text, kind, before, after, id, note }.
 * kind='skip' означает "не сжимали"; text при этом равен входу байт в байт.
 *
 * Дело берется из opts.caseId либо выводится из opts.fromPath. Ни одно поле профиля отсюда в
 * Метиду не уезжает: что бы вызывающий ни подал, режется профилем audit без overrides.
 */
export async function squeezeText(text, opts = {}) {
  const src = String(text)
  const before = Buffer.byteLength(src, 'utf8')
  const label = safeLabel(opts.label)
  const asIs = (note) => ({ text: src, kind: 'skip', before, after: before, id: null, note })

  const caseId = opts.caseId ? String(opts.caseId).normalize('NFC') : caseFromPath(opts.fromPath)
  if (!caseId) {
    // Fail-closed в данных: без дела нет изоляции, а без изоляции сжимать нельзя.
    return asIs('метида: дело не выведено из пути, сжатие не применялось (изоляция памяти дороже экономии)')
  }
  const slot = slotOf(caseId)
  // Замер без ключа ложится БЕЗЫМЯННЫМ, и вызывающий об этом слышит. Подставить сюда несоленый
  // хеш было бы тише, но это и есть та дыра, которую чиним: слот снова брался бы словарем.
  const slotNote = slot ? null : `метида: ${slotKeyReason}, дело в замере не названо`

  if (!squeeze) {
    // Fail-open в трафике: дома Метиды нет - дом Фемиды работает как работал, без сжатия.
    const jerr = journal(record({ label, slot, before, after: before, r: null, id: null, engine: null }))
    return asIs(notes(`метида: сжатие выключено - ${offReason}`, slotNote, jerr))
  }

  // Маркеры несут АБСОЛЮТНЫЕ команды: их читает агент с чужим cwd, и относительный путь там не
  // резолвится. Короткие формы самой Метиды путей не знают (L2 не смотрит в L3), поэтому дом
  // подает свои генераторы. У маркера выноса стоит ИМЯ ДЕЛА: без дела оригинал не резолвится,
  // это и есть изоляция, доведенная до команды. CLI Метиды тут не годится намеренно - ее
  // `restore --id` смотрит в общий каталог ~/.metiz/ccr и про каталоги дел не знает. Имя дела в
  // маркере стоит рядом с документом этого же дела, то есть ничего нового о клиенте не
  // рассказывает; в журнал оно при этом не попадает никогда.
  // Команда разворота читает свернутый текст со stdin - так же, как ее зовет дом Гелиоза.
  // Машинная часть строки (версия, sha оригинала, цепочка шагов) приходит от конвейера полем head:
  // разбирает ее регексп Метиды, и вторая сборка разошлась бы с ним при первой правке. Прибитая
  // здесь 'v1' пережила бы переход Метиды на v2 и молча ломала бы разворот. METIZ_HOME в команде
  // не ставится намеренно: expand хранилища не касается, а дом состояния у Фемиды свой, покаталогу
  // дела, и подставлять сюда общий каталог значило бы указать не туда.
  const foldMarker = (f) => `${f.head} · было ${kb(f.before)} → ${kb(f.after)} · оригинал: ` +
    `node ${path.join(METIZ, 'src/cli/main.ts')} expand]`
  // Маркер выноса ИМЕНИ ДЕЛА не несет и нести не может. Раньше в него шло
  // `дело cases/<клиент>/<дело>` вместе с командой restore --case, а маркер ложится в ТЕКСТ,
  // который читает модель. Имя доверителя - персональные данные, и текст уходит за границу
  // процесса: любой проход, на котором рождается ccr-результат, выносил бы имя наружу.
  // Живой прогон через собственный шов дома (THEMIS_METIZ_DIR) это показал дословно.
  //
  // Заглушка стоит потому, что текст с этим маркером наружу не уходит НИКОГДА: ниже
  // ccr-результат отвергается целиком. Генератор все равно обязан быть - конвейер зовет его сам.
  const ccrMarker = () => '[themis:ccr]'

  let r
  try {
    r = squeeze(src, { profile: PROFILE, marker: ccrMarker, foldMarker })
  } catch (e) {
    // Fail-open в трафике: сломалось сжатие - отдаем вход как есть, работа дома не встает.
    return asIs(`метида: ${e && e.message || e}`)
  }
  if (!r.steps.some(s => s.applied)) {
    const jerr = journal(record({ label, slot, before, after: before, r, id: null, engine: 'metiz' }))
    return asIs(notes(slotNote, jerr))
  }

  // ВЫНОС СОДЕРЖИМОГО ОТВЕРГАЕТСЯ. Профиль дома один - audit, и вынос он запрещает по построению
  // (allowLossy: false снимает необратимый шаг, metiz/src/router/pipeline.ts:386). Значит
  // ccr-результат под audit - НАРУШЕНИЕ КОНТРАКТА конвейера, а не рабочий случай, и ответ на
  // нарушение fail-closed: оригинал на диск НЕ ложится, сжатое НЕ выдается, наружу уходит вход
  // байт в байт. Доктрина 2 при этом держится сама собой: выход не изменен - восстанавливать
  // нечего.
  //
  // Второй возможный ответ - непрозрачный локальный ключ в маркере вместо имени дела - выбран НЕ
  // был, и вот почему. Он потребовал бы завести на диске указатель «ключ -> дело», то есть НОВОЕ
  // постоянное место, где имя доверителя лежит вне дерева cases, со своим сроком жизни и своей
  // уборкой; в юридическом доме это второй экземпляр сведений об адвокатской тайне мимо описи.
  // Платить этим за ветку, которой под единственным профилем дома быть не должно, - плохая сделка.
  // Появится профиль с законным выносом - ключ и указатель заводятся тогда же, вместе с его
  // дисциплиной хранения.
  if (r.ccrIds.length > 0) {
    const jerr = journal(record({ label, slot, before, after: before, r, id: null, engine: 'metiz' }))
    const note = 'метида: проход вернул вынос в хранилище, чего профиль audit не допускает; ' +
      'сжатое не выдаем и оригинал на диск не кладем'
    return asIs(notes(note, slotNote, jerr))
  }
  const id = null

  const jerr = journal(record({ label, slot, before, after: r.after, r, id, engine: 'metiz' }))
  const note = notes(slotNote, jerr)
  return {
    text: r.text,
    kind: r.reversible ? 'reformat' : 'offload',
    before,
    after: r.after,
    id,
    ...(note ? { note } : {}),
  }
}

/**
 * Оригинал по делу и id. Байт в байт или отказ - пустая строка тут запрещена.
 * Чужой id под своим делом не резолвится: это и есть изоляция памяти.
 *
 * Дело приходит ЗАКРЫТЫМ каналом (--case-fd), а не из argv: см. readClosedFd.
 */
export async function restoreText(caseId, id) {
  if (!openSharedStore) throw new Error(`метида: восстановление недоступно - ${offReason}`)
  const c = String(caseId ?? '').normalize('NFC')
  if (!c) throw new Error('метида: не названо дело (--case-fd N)')
  const t = await storeFor(c).get(String(id ?? ''))
  // Дело названо СЛОТОМ, а не путем, и это не косметика сообщения. Промах по id - штатный исход
  // (чужой id под своим делом обязан не резолвиться), а каждый такой отказ уезжал в stderr
  // строкой `cases/<клиент>/<дело>`, то есть именем доверителя целиком. Ловится он в самом низу
  // файла и уходит в диагностику запуска - за границу процесса, куда имени клиента нельзя.
  // Слот тот же, что в журнале замеров (case_slot, HMAC на ключе дома): отказ сходится с записью
  // замера по одному ключу и при этом никого не называет. Своего идентификатора здесь не
  // заводится - второй способ назвать дело развел бы отказ и журнал.
  //
  // Ключа нет - дело в отказе не называется НИКАК. Ни имени, ни несоленого хеша: первое и есть
  // персональные данные, второе к ним сводится словарем. Путь к ключу сюда тоже не печатается -
  // отказ уезжает в диагностику запуска, и лишней топологии диска там делать нечего.
  if (t === null) {
    const s = slotOf(c)
    throw new Error(`метида: оригинал ${id} не найден под делом ` +
      (s ? `slot=${s}` : '(слот не посчитан: ключ слота недоступен)'))
  }
  return t
}

// --- CLI ------------------------------------------------------------------------------------

function arg(argv, name) {
  const i = argv.indexOf('--' + name)
  return i >= 0 && i + 1 < argv.length ? argv[i + 1] : null
}

/**
 * Единственная дверь для всего, из чего выводится имя доверителя: значение приходит ЗАКРЫТЫМ
 * каналом - отдельным дескриптором, а не argv. Каналов таких два, и оба ходят сюда: путь к
 * материалу (--path-fd) и само дело (--case-fd).
 *
 * Раньше путь стоял в argv (`--from-path /…/cases/<КЛИЕНТ>/<дело>/…`), и живой прогон показал
 * имя доверителя в выдаче `ps -ww -A -o args` - 11 попаданий за 0.56 с работы моста. Argv виден
 * любому процессу владельца и уезжает в диагностику запуска; это граница процесса, а за нее имя
 * клиента не выходит. Окружение сюда не годится по той же причине: `ps -E` показывает и его.
 *
 * Дело в argv было той же дырой и той же ценой, просто чинили ее не тогда: путь дела - это и
 * есть имя доверителя, потому что дело записано как cases/<клиент>/<дело>. [замер] на одном
 * проходе `squeeze --case cases/<КЛИЕНТ>/dolg-2026 --file …` имя доверителя стояло в argv моста
 * в 11 срезах из 400 снятых подряд `ps -ww -A -o args` (совпадение с числом выше случайно: там
 * мерили другой флаг). Поэтому --case и --file сняты (см. SNYATY), а не оставлены «на всякий».
 *
 * Номер дескриптора в argv остается, но номер - это цифра, а не персональные данные.
 * Дескриптор читается до конца и закрывается: канал одноразовый.
 *
 * ГРАНИЦА ЧЕСТНОСТИ, ее надо знать вслух. Слой отвечает за СВОЙ argv и только за него. Кто
 * наполняет дескриптор - отвечает за свой: `printf 'cases/…' | node … --case-fd 0` кладет имя
 * доверителя в argv самого printf, и ps увидит его там. Закрыть это изнутри слоя нечем.
 * Фасад дома (scripts/themis_metiz.py) делает правильно: os.pipe() и os.write() внутри своего
 * процесса, без единого стороннего argv, - на него и равняться вызывающим.
 */
function readClosedFd(nomer) {
  if (nomer === null) return null
  const fd = Number(nomer)
  if (!Number.isInteger(fd) || fd < 0) return null
  try {
    const s = readFileSync(fd, 'utf8')
    return s.length ? s : null
  } catch {
    // Fail-open в трафике: канал не прочитался - пути нет, дела нет, сжатия нет.
    return null
  } finally {
    try { closeSync(fd) } catch { /* закрывать нечего */ }
  }
}

/**
 * Синхронная выдача в дескриптор. process.stdout.write в трубу асинхронен, а process.exit
 * обрывает недописанное: замером поймано ровно это - оригинал на 104 КБ приезжал огрызком в
 * 65536 байт, и потребитель принимал огрызок за целый документ. Обрыв трубы не проглатываем:
 * молчаливый код 0 на половине оригинала - худший из возможных исходов восстановления.
 */
function writeOut(fd, data) {
  try {
    writeFileSync(fd, data)
    return true
  } catch (e) {
    if (e && e.code === 'EPIPE') return false
    throw e
  }
}

// Флаги, снятые за то, что несли имя доверителя в argv. Каждый брал ПУТЬ ДЕЛА, а путь дела и
// есть имя доверителя: cases/<клиент>/<дело>.
//
// Отказ громкий, потому что тихий тут хуже. Убрать разбор и промолчать значило бы, что старый
// вызов остается без дела и не сжимает вовсе (fail-closed сработал бы), но имя доверителя все
// равно постоит в его argv и в ps - то есть утечка сохранилась бы, а сигнала о ней не было бы
// ни одного. Отказ на входе останавливает процесс раньше любой работы.
//
// Единственный боевой потребитель CLI - scripts/themis_metiz.py, и он зовет только
// `squeeze --path-fd N --label МЕТКА` с телом на stdin: снятие ни одного из этих флагов его не
// касается. Других вызовов в доме нет (`--case` из quality_gate.py - чужой прибор и чужой флаг).
const SNYATY = {
  case: 'дело подается дескриптором: --case-fd N',
  file: 'тело подается на stdin',
  'from-path': 'путь к материалу подается дескриптором: --path-fd N',
}

async function cli(argv) {
  const cmd = argv[0]
  // Сверяются ОБЕ формы флага: точное имя и приклеенное значение `--флаг=ЗНАЧЕНИЕ`. Прошлая
  // версия сторожа смотрела только argv.includes('--file'), и форма с равенством обходила его
  // молча. Обманчива она тем, что выглядит безобидно: arg() формы с '=' не разбирает вовсе,
  // значение никуда не доезжает, работа идет без дела и без сжатия - как будто ничего и не
  // случилось. Но значение при этом СТОИТ В ARGV, а argv и есть та граница, ради которой флаги
  // снимались. [замер] живым прогоном до правки: `squeeze --file=<путь дела> --label proba`
  // отработал с кодом 0, сторож промолчал, и путь дела нашелся в 5 срезах `ps -ww -A -o args`
  // из 5 снятых подряд за время работы моста.
  //
  // Значение снятого флага НЕ печатается ни в каком виде: оно и есть то, что нельзя выпускать.
  for (const flag of Object.keys(SNYATY)) {
    const tochno = '--' + flag
    if (!argv.some(a => a === tochno || a.startsWith(tochno + '='))) continue
    writeOut(2, `метида: флаг --${flag} снят - его значение стояло в argv, а argv видит любой ` +
      `процесс владельца через ps. Замена: ${SNYATY[flag]}\n`)
    return 2
  }
  if (cmd === 'squeeze') {
    // Тело только со stdin. --file принимал путь материала, то есть возвращал имя доверителя в
    // argv через заднюю дверь, и он же служил запасным источником дела (`|| file`) - оставить
    // его значило бы закрыть --case и тут же открыть тот же канал под другим именем.
    const src = readFileSync(0, 'utf8')
    const r = await squeezeText(src, {
      fromPath: readClosedFd(arg(argv, 'path-fd')),
      label: arg(argv, 'label'),
    })
    const whole = writeOut(1, Buffer.from(r.text, 'utf8'))
    // Причина всегда уходит в stderr, а не в stdout: stdout - это текст для модели, и подмешивать
    // в него служебную строку значит отдать модели то, чего в документе не было.
    if (r.note) writeOut(2, r.note + '\n')
    if (!whole) { writeOut(2, 'метида: труба закрыта, текст доехал не целиком\n'); return 1 }
    return 0
  }
  if (cmd === 'restore') {
    // Отказ громкий и с кодом 1 (бросок ловится ниже): молчаливый пустой вывод потребитель
    // примет за оригинал - ровно тот баг, от которого хранилище и спасает.
    const t = await restoreText(readClosedFd(arg(argv, 'case-fd')), arg(argv, 'id'))
    if (!writeOut(1, Buffer.from(t, 'utf8'))) {
      writeOut(2, `метида: труба закрыта до конца выдачи, оригинал ${arg(argv, 'id')} доехал не целиком\n`)
      return 1
    }
    return 0
  }
  writeOut(2, [
    'themis-metiz - врезка Метиды в дом Фемиды (профиль audit, изоляция по делу)',
    '',
    'Дело записано как cases/<клиент>/<дело>, то есть САМ путь дела - имя доверителя. Поэтому ни',
    'путь, ни дело в argv не подаются: argv виден любому процессу владельца через ps. Оба',
    'приходят дескриптором, в argv остается только его номер.',
    '',
    '  squeeze --path-fd N [--label МЕТКА]   тело на stdin; путь к материалу читается',
    '                                        из дескриптора N',
    '  restore --case-fd N --id <sha>        дело читается из дескриптора N',
    '  --selftest',
    '',
    'Наполнять дескриптор внутри своего процесса (os.pipe + os.write), а не через стороннюю',
    'команду: `printf cases/… | …` вернет имя доверителя в ps через argv самого printf.',
    'Образец правильного вызова - scripts/themis_metiz.py.',
    '',
    `журнал: ${JOURNAL}`,
    `Метида: ${METIZ || 'НЕ НАЙДЕНА (' + offReason + ')'}`,
  ].join('\n') + '\n')
  return 2
}

