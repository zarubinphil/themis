#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""M09 — сборка отчета по корпусу ИЗ СЫРОЙ УЛИКИ прогона.

Зачем прибор, а не руки. Три круга приемки подряд отчет был красным по одной и
той же причине: числа в нем не сходились с прогоном, а сам он был снят РАНЬШЕ
правки кода. Пока отчет переписывается руками, эта ошибка воспроизводима.
Здесь он выводится из json прогона, и разойтись с уликой не может.

Свежесть проверяется УТВЕРЖДЕНИЕМ, а не на глаз: улика обязана быть моложе
кода, который она меряет. Иначе прибор отказывается собирать отчет.

    python3 scripts/_m09_korpus_otchet.py \
        .helioz/state/plan/_m09_progon.json .helioz/state/plan/M09-korpus-otchet.md
"""
import hashlib
import json
import os
import sys
import time

MERYAEMYE = ["scripts/markdown_extract.py", "scripts/render_tail.py"]


def sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()[:16]


def stamp(ts):
    return time.strftime("%d.%m.%Y %H:%M:%S", time.localtime(ts))


def main():
    src, dst = sys.argv[1], sys.argv[2]
    ulika_mtime = os.path.getmtime(src)

    # ВОРОТА СВЕЖЕСТИ: улика моложе кода, который она меряет.
    for p in MERYAEMYE:
        kod = os.path.getmtime(p)
        if kod > ulika_mtime:
            sys.exit(f"ОТКАЗ: {p} правлен {stamp(kod)} ПОЗЖЕ улики {stamp(ulika_mtime)}. "
                     f"Отчет был бы снят не с того кода — гони прогон заново.")

    d = json.load(open(src, encoding="utf-8"))
    rows = d["rows"]
    lost, gained = d["pages_lost_ocr"], d["pages_gained_ocr"]
    verdict = ("ПОТЕРИ НЕТ НИ В ОДНУ СТОРОНУ" if lost == 0
               else f"ПОТЕРЯ OCR НА {lost} СТРАНИЦАХ — сработал пункт stop задачи")

    L = []
    a = L.append
    a(f"# M09 — прогон корпуса: старый путь MuPDF против шипнутого кода ({stamp(ulika_mtime)})\n")
    a("Собран прибором `scripts/_m09_korpus_otchet.py` из сырой улики прогона —")
    a("руками не переписывался, разойтись с уликой не может.\n")
    a(f"- прогон снят прибором `scripts/_m09_korpus_progon.py`, сырая улика `{src}`")
    a(f"  ({os.path.getsize(src)} байт, {stamp(ulika_mtime)});")
    for p in MERYAEMYE:
        a(f"- меряемый код `{p}`: sha256 `{sha(p)}`, правлен {stamp(os.path.getmtime(p))};")
    a(f"- отчет собран {stamp(time.time())} — ПОЗЖЕ и кода, и улики (проверено утверждением).\n")
    a("База сравнения — то, как PDF читался ДО замены движка: fitz (MuPDF) постранично.")
    a("Новый путь — `pdf_perpage_chars` как он шипнут: pypdfium2 основной, постраничный")
    a("запасной MuPDF по правилу минимума (решение владельца 02.09.2026, круг 4).\n")
    a(f"Порог `TEXT_MIN = {d['text_min']}` не двигался: прогон проверяет это утверждением")
    a("в начале работы, иначе он недействителен.\n")
    a(f"Корпус: {d['total']} PDF. Прочитано: {d['read']}. Ошибок чтения: {len(d['errors'])}.\n")

    a(f"## ВЕРДИКТ: {verdict}\n")
    a("Критерий приемки (б) требует доказать обе стороны отдельно. Они доказаны числом:\n")
    a("| сторона потери | что значит | требование | замер |")
    a("|---|---|---|---|")
    a(f"| страница потеряла OCR | у старой базы MuPDF страница была сканом, а новый путь "
      f"считает ее текстовой — OCR бы НЕ запустился, фактура теряется | **ровно 0** | **{lost}** |")
    a(f"| страница добавила OCR | обратное: множество сканов расширилось | разрешено | {gained} |")
    a(f"| текстовый слой взят у MuPDF | PDFium прочел меньше — текст берется у MuPDF, "
      f"слой не теряется | по факту | {d['pages_text_from_mupdf']} стр. "
      f"в {len(d['materials_text_from_mupdf'])} материалах |")
    a("")
    a("Почему нуля в первой строке достаточно, а не случайность: решение стороны порога —")
    a("`dec = min(PDFium, MuPDF)`, то есть `dec <= MuPDF` на КАЖДОЙ странице. Если старая")
    a("база считала страницу сканом (`MuPDF < TEXT_MIN`), то и `dec < TEXT_MIN`. Множество")
    a("сканов может только расширяться — прогон по корпусу это подтверждает, а не заменяет.\n")

    if d["materials_lost_ocr"]:
        a("### Материалы, потерявшие OCR (требуется ноль)\n")
        for i in d["materials_lost_ocr"]:
            a(f"- `{i}`")
        a("")

    a("## Материалы, где маршрут изменился\n")
    a("| материал | стр. | симв. ДО (MuPDF) | симв. ПОСЛЕ (min) | сторона ДО | сторона ПОСЛЕ | "
      "стр. потеряло OCR | стр. добавило OCR | стр. текста от MuPDF |")
    a("|---|---|---|---|---|---|---|---|---|")
    interesting = [r for r in rows
                   if r["page_flips"] or r["mupdf_text_pages"] or r["old_side"] != r["new_side"]]
    for r in sorted(interesting, key=lambda r: -r["mupdf_text_pages"] - r["page_flips"]):
        a(f"| {r['id']} | {r['pages']} | {r['old_chars']} | {r['new_chars']} | {r['old_side']} | "
          f"{r['new_side']} | {r['lost_ocr']} | {r['gained_ocr']} | {r['mupdf_text_pages']} |")
    a(f"\nВсего таких материалов: {len(interesting)} из {d['read']}. Остальные читаются")
    a("обоими движками одинаково по стороне порога.\n")
    a("Идентификатор — SHA-256 относительного пути, первые 10 знаков. Имена файлов дел")
    a("в отчет не идут ни в таблице, ни в объявлениях ниже: обезличивание делает прибор")
    a("прогона, а не рука.\n")

    a("## Запасной путь объявлен вслух (stderr прогона, как есть)\n")
    a("Молчаливый запасной путь неотличим от отсутствия основного, поэтому каждая")
    a("замена маршрута печатается с идентификатором материала, номером страницы и причиной.\n")
    a("```")
    shown = 0
    for r in rows:
        if r["announce"] and shown < 12:
            for line in r["announce"].splitlines():
                if shown < 12:
                    a(line)
                    shown += 1
    a("```\n")
    a(f"Объявлений всего в {len(d['fallback_used'])} материалах корпуса.\n")

    a("## Лицензия — блокер отложен, а не снят\n")
    a("Постраничный запасной путь делает обращений к AGPL-пакету PyMuPDF БОЛЬШЕ, а не меньше.")
    a("Решение владельца 02.09.2026: пакет остается. AGPL-3.0 §5 включается при распространении,")
    a("§13 — при сетевом взаимодействии. Пока пакет в ядре, публичная выкладка и продажа закрыты.")
    a("Пункт обязан всплыть в приемке очереди публикации.")

    open(dst, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"отчет собран: {dst} ({os.path.getsize(dst)} байт), потеря OCR: {lost} стр.")


if __name__ == "__main__":
    main()
