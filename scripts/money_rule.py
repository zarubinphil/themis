#!/usr/bin/env python3
"""money_rule.py — единый денежный разбор проекта: валюты, числительные, цитаты.

Две копии денежного правила — в `verdict.py` (наличие прописи в .md) и в
`document_guard.py` (наличие и СОВПАДЕНИЕ прописи в .docx) — разошлись, и
круг 9 этапа 9.22 собрал счет этому расхождению:

  · сторож формата дословную цитату в елочках исключал, вердикт — нет, и
    возражение/жалоба, цитирующие обжалуемый акт с суммой («суд указал:
    «взыскать 100 000 рублей»»), не могли получить вердикт вовсе;
  · словари валют разошлись: вердикт знал доллары и евро, сторож формата —
    только рубли, и «200 000 (сто) долларов США» (расхождение в 2000 раз)
    проходило оба гейта;
  · числительное опознавалось префиксом со свободным хвостом: «однако»
    принималось за числительное, а «девяносто» и «полтора» — нет;
  · нулевые копейки словом («ноль копеек») были в исключении, а цифрами
    («00 копеек») — нет, и стандартная форма «50 000,00 (пятьдесят тысяч
    рублей 00 копеек)» браковалась.

Здесь — ОДИН источник для обоих приборов:

  · CURRENCIES / CUR_RE / currency_of — словарь валют проекта (форма слова,
    род числительного, склонение единицы параметром валюты);
  · NUMERAL_WORDS / is_numeral / numeral_tail — словарь числительных из
    словоформ собственного прибора `propis.py` (точное слово, не префикс);
  · split_quotes — дословная цитата в елочках: не ТРЕБОВАТЬ пропись
    (цитировать обязаны дословно), но присутствующую сверять;
  · money_int — разбор числа (разряды пробелом/неразрывным/точкой, копейки
    запятой);
  · strip_currency_tail — СТРУКТУРНЫЙ разбор хвоста прописи: «… рублей
    00 копеек» цифрами — тот же обиход, что «ноль копеек» словом;
  · propis_variants / words_match / propis_word — сверка прописи по шести
    падежам через `propis.py`; polutora_value — «полтора миллиона».

Якоря самих сумм (регулярки числа и места прописи) остаются в приборах:
у вердикта и сторожа формата разные задачи — наличие прописи в плоском
тексте .md и совпадение прописи в структуре .docx. Расхождение было не в
якорях, а в словарях и правилах разбора — они и сведены сюда.
"""
from __future__ import annotations

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import propis as _propis  # noqa: E402  свой конвертер числительных, fail-closed при отсутствии

# ── Валюты: ОДИН словарь на проект ─────────────────────────────────────────
# gender — род согласования числительного («один рубль», «одна копейка»);
# forms — склонение единицы (1 / 2-4 / 5+) параметром валюты: подсказка
# обязана назвать «долларов», когда валюта — доллар, а не зашитые «рублей»;
# minor — мелкая единица (рубль → копейка, доллар/евро → цент): её род и
# склонение берутся той же строкой словаря.
CURRENCIES = {
    "рубль": {
        "gender": "м",
        "forms": ("рубль", "рубля", "рублей"),
        "minor": "копейка",
        "words": r"руб(?:\.|л[а-я]*)?|₽|р\.",
    },
    "копейка": {
        "gender": "ж",
        "forms": ("копейка", "копейки", "копеек"),
        "minor": None,
        "words": r"коп(?:\.|е[а-я]*)?",
    },
    "доллар": {
        "gender": "м",
        "forms": ("доллар", "доллара", "долларов"),
        "minor": "цент",
        "words": r"доллар[а-я]*|долл\.?|usd|\$",
    },
    "евро": {
        "gender": "м",
        "forms": ("евро", "евро", "евро"),
        "minor": "цент",
        "words": r"евро|eur|€",
    },
    "цент": {
        "gender": "м",
        "forms": ("цент", "цента", "центов"),
        "minor": None,
        "words": r"цент[а-я]*",
    },
}

# Единый шаблон слова валюты и граница после него. «р.» требует цифры перед
# собой и не задевает «стр.»/«г.» — те не идут за суммой; граница слова после
# точки не строится \b, поэтому хвост закрыт явным запретом буквы.
CUR_RE = "|".join(f"(?:{c['words']})" for c in CURRENCIES.values())
CUR_END = r"(?![A-Za-zА-Яа-яЁё])"

# Крупные и мелкие единицы: префиксы слов для структурного разбора прописи.
MAJOR_PREFIXES = ("руб", "доллар", "долл", "евро")
MINOR_PREFIXES = ("коп", "цент")


def currency_of(token: str) -> str | None:
    """Каноническое имя валюты по слову/символу из текста («рублей», «USD», «€»)."""
    t = token.strip().lower()
    if not t:
        return None
    for name, info in CURRENCIES.items():
        if re.fullmatch(rf"(?:{info['words']})", t, re.I):
            return name
    return None


# ── Числительные: СЛОВАРЬ словоформ propis.py, а не префикс ────────────────
# Прежнее опознание префиксом со свободным хвостом («оди?н» + \w*) принимало
# «однако» за числительное и пропускало сумму «однако (100 000) рублей», а
# руками добавленные «тридцать/сорок/пятьдесят» забыли «девяносто» и
# «полтора» — верная пропись браковалась (этап 9.22, круг 9). Словарь
# строится из таблиц собственного конвертера: что прибор умеет писать, то
# сторож и узнает — ни больше, ни меньше.
def _load_numeral_words() -> frozenset:
    words = set()
    tables = [_propis._ZERO]
    tables += list(_propis._ONES_PLAIN.values())
    for gendered in _propis._ONES_GENDERED.values():
        tables += list(gendered.values())
    tables += list(_propis._TEENS.values())
    tables += list(_propis._TENS.values())
    tables += list(_propis._HUNDREDS.values())
    for sg, pl in _propis._SCALES.values():
        tables += [sg, pl]
    for table in tables:
        words.update(w.lower() for w in table.values())
    # Формы вне таблиц propis.py: «нуль» (обиход наряду с «ноль») и
    # «полтора» (полторы тысячи/миллиона — живая форма денежных требований;
    # значение сверяет polutora_value, а не конвертер).
    words |= {"нуль", "нуля", "нулю", "нулем", "нуле",
              "полтора", "полторы", "полутора"}
    return frozenset(words)


NUMERAL_WORDS = _load_numeral_words()


def is_numeral(word: str) -> bool:
    """Слово ЦЕЛИКОМ — числительное из словаря propis.py (не префикс)."""
    return word.lower() in NUMERAL_WORDS


def numeral_tail(words: list[str]) -> list[str]:
    """Хвост фразы из числительных: «взыскать с ответчика девяносто тысяч»
    → [девяносто, тысяч]. Нечислительное слово обрывает хвост."""
    tail = []
    for w in reversed(words):
        if is_numeral(w):
            tail.insert(0, w)
        else:
            break
    return tail


_SCALE_VALUES = (("тысяч", 1_000), ("миллион", 1_000_000), ("миллиард", 1_000_000_000))


def polutora_value(tail: list[str]) -> int | None:
    """«полтора миллиона» / «полторы тысячи» → значение (1 500 000 / 1 500).

    Конвертер propis.py такую форму не порождает, но в денежных требованиях
    она обиходна; сверяется структурно: полтора + разрядное слово."""
    if len(tail) == 2 and tail[0] in ("полтора", "полторы"):
        for pref, val in _SCALE_VALUES:
            if tail[1].startswith(pref):
                return val * 3 // 2
    return None


# ── Дословная цитата в елочках ─────────────────────────────────────────────
# Цитата нормы или судебного акта воспроизводится как в источнике — ТРЕБОВАТЬ
# там пропись значит запретить цитирование (правило проекта — цитировать
# дословно). Но пропись, которая в цитате ЕСТЬ, обязана совпадать с числом:
# подмена суммы внутри елочек — та же ложь. Поэтому цитаты вырезаются из
# основного текста и судятся отдельным проходом в режиме «не требовать,
# но сверять» (проба круга 6, 20.08.2026; расхождение копий — круг 9).
QUOTE_RE = re.compile(r"«[^»]*»")


def split_quotes(text: str) -> tuple[str, list[str]]:
    """(текст без цитат, список цитат без елочек)."""
    quotes = [m.group(0)[1:-1] for m in QUOTE_RE.finditer(text)]
    return QUOTE_RE.sub(" ", text), quotes


# ── Разбор числа ───────────────────────────────────────────────────────────
def money_int(num_raw: str) -> tuple[str, str | None]:
    """Целая часть и копейки найденного числа: пробелы (в т.ч. неразрывный
    U+00A0, узкий U+202F, тонкий U+2009) и точки между тройками — разряды,
    запятая — копейки. Запятая между ТРОЙКАМИ («1,250,000») — тоже разряды:
    две и более группы по три цифры после запятой копейками не бывают
    (проба круга 6, 20.08.2026)."""
    s = (num_raw.replace("\u00a0", " ").replace("\u202f", " ")
         .replace("\u2009", " ").strip())
    kop = None
    if re.fullmatch(r"\d{1,3}(?:,\d{3})+", s):
        return s.replace(",", ""), None
    if "," in s:
        s, kop = s.split(",", 1)
    s = s.replace(" ", "")
    if re.fullmatch(r"\d{1,3}(?:\.\d{3})+", s):
        s = s.replace(".", "")
    return s, kop


# ── Склонение единицы валюты параметром ────────────────────────────────────
def sklonenie(n: int, forms: tuple[str, str, str]) -> str:
    """Форма единицы после числительного: 1 рубль, 2 рубля, 5 рублей —
    словарь форм параметром, а не зашитые «рубль/рубля/рублей»."""
    odna, dve, pyat = forms
    n = abs(n) % 100
    if 11 <= n <= 14:
        return pyat
    n %= 10
    return odna if n == 1 else dve if 2 <= n <= 4 else pyat


# ── Сверка прописи с числом ────────────────────────────────────────────────
def propis_word(n: int, gender: str = "м", case: str = "им") -> str:
    """Пропись числа в одной форме (обертка над propis.py для подсказок)."""
    return _propis.propis(n, gender=gender, case=case)


def propis_variants(n: int, gender: str = "м") -> list[list[str]]:
    """Все шесть падежей числа словами. Сумма в документе склоняется по
    синтаксису фразы («взыскать одну тысячу», «к одной тысяче», «одной
    тысячей») — сверка обязана принимать любой падеж, но ложь ловить в
    каждом (проба круга 6: сверка знала только именительный, и просительная
    часть иска объявлялась браком)."""
    out = []
    for c in _propis.CASES:
        try:
            out.append(_propis.propis(n, gender=gender, case=c).split())
        except ValueError:
            pass
    return out


def words_match(words: list[str], variants: list[list[str]]) -> bool:
    """Сверка по словам целиком: «пять» внутри «пятьдесят» и префикс
    «одна тысяча» в «одна тысяча двести» совпадением не считаются."""
    return any(words == v for v in variants)


def strip_currency_tail(words: list[str]) -> tuple[bool, list[str]]:
    """Валюта внутри прописи — СТРУКТУРНО, а не списком слов-исключений.

    Последнее слово «рубл…/доллар…/евро/копе…/цент…» — та же денежная сумма
    («1 000 (сто тысяч рублей)»). Полная форма «… рублей 00 копеек» — валюта
    после числительных и НУЛЕВАЯ мелкая единица словом («ноль») или цифрами
    («00») — обиходная, несовпадением не является: цифровая форма «00 копеек»
    — стандарт процессуального документа (этап 9.22, круг 9: словом нулевые
    копейки были в исключении, цифрами — нет).
    """
    if not words or not words[-1].startswith(MAJOR_PREFIXES + MINOR_PREFIXES):
        return False, words
    nul = next((i for i, w in enumerate(words[:-1])
                if w.startswith(MAJOR_PREFIXES)), None)
    if nul is not None and words[-1].startswith(MINOR_PREFIXES):
        middle = words[nul + 1:-1]
        if middle in (["ноль"], ["нуль"]) or (
                middle and all(re.fullmatch(r"\d+", w) and int(w) == 0
                               for w in middle)):
            return True, words[:nul]
    return True, words[:-1]


def selftest() -> int:
    checks = [
        ("валюта опознается во всех формах",
         [currency_of(t) for t in ("рублей", "руб.", "р.", "₽", "копеек",
                                   "долларов", "USD", "$", "евро", "EUR", "€",
                                   "центов")]
         == ["рубль", "рубль", "рубль", "рубль", "копейка", "доллар",
             "доллар", "доллар", "евро", "евро", "евро", "цент"]),
        ("не валюта не опознается", currency_of("шт") is None),
        # Числительное — словарь, не префикс: обе оси круга 9.
        ("«однако» — НЕ числительное", not is_numeral("однако")),
        ("«девяносто» — числительное", is_numeral("девяносто")),
        ("«полтора» — числительное", is_numeral("полтора")),
        ("«тридцать» и падежи — числительные",
         is_numeral("тридцать") and is_numeral("пятидесяти")
         and is_numeral("одной")),
        ("хвост числительных", numeral_tail(
            "взыскать с ответчика девяносто тысяч".split())
         == ["девяносто", "тысяч"]),
        ("полтора миллиона — значение", polutora_value(
            ["полтора", "миллиона"]) == 1_500_000),
        ("полторы тысячи — значение",
         polutora_value(["полторы", "тысячи"]) == 1_500),
        # Цитата: вырезается из основного текста, возвращается на сверку.
        ("цитата вырезается",
         split_quotes('суд указал: «взыскать 100 000 рублей», не установив')
         [0].strip() == "суд указал:  , не установив"),
        ("цитата возвращается",
         split_quotes('суд указал: «взыскать 100 000 рублей»')[1]
         == ["взыскать 100 000 рублей"]),
        # Хвост прописи структурно: нулевые копейки словом и цифрами — обиход.
        ("нулевые копейки словом", strip_currency_tail(
            "пятьдесят тысяч рублей ноль копеек".split())
         == (True, ["пятьдесят", "тысяч"])),
        ("нулевые копейки ЦИФРАМИ — тот же обиход", strip_currency_tail(
            "пятьдесят тысяч рублей 00 копеек".split())
         == (True, ["пятьдесят", "тысяч"])),
        ("валюта последним словом", strip_currency_tail(
            "сто тысяч рублей".split()) == (True, ["сто", "тысяч"])),
        ("не валюта не вычитается", strip_currency_tail(
            "сто тысяч штук".split()) == (False, ["сто", "тысяч", "штук"])),
        ("число с копейками", money_int("38 998,29") == ("38998", "29")),
        ("разряды запятой", money_int("1,250,000") == ("1250000", None)),
        ("склонение параметром валюты",
         sklonenie(1, CURRENCIES["доллар"]["forms"]) == "доллар"
         and sklonenie(5, CURRENCIES["доллар"]["forms"]) == "долларов"
         and sklonenie(2, CURRENCIES["копейка"]["forms"]) == "копейки"),
    ]
    for name, ok in checks:
        print(f"  {'✓' if ok else '✗'} {name}")
    bad = [n for n, ok in checks if not ok]
    print(f"selftest {'пройден' if not bad else 'ПРОВАЛЕН'}: "
          f"{len(checks) - len(bad)}/{len(checks)}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(selftest())
