#!/usr/bin/env bash
# scripts/gate.sh — тонкая обертка над существующими приборами Фемиды.
#
# Задача одна: запустить прибор, показать его вывод ЦЕЛИКОМ и вернуть ЕГО код
# возврата — что бы ни стояло дальше в конвейере.
#
# Прецедент 21.02 (корень №5): сторож напечатал «нарушений 1, Пересобрать .docx»,
# а «$?» рядом дал 0 — потому что читался ПОСЛЕ трубы и относился к последней
# команде трубы, а не к прибору. Отказ стал неотличим от успеха, и последняя
# редакция судебного документа ушла к рецензенту непроверенной.
#
# Лечение: код берется из PIPESTATUS[0] (самого прибора), а не из «$?» после труб
# показа. Вызывать вместо голого прибора:
#     scripts/gate.sh python3 scripts/document_guard.py ФАЙЛ.docx
# и читать код возврата gate.sh — он равен коду прибора, трубы показа его не трут.
#
# ГРАНИЦА: код обертки читать БЕЗ трубы после нее.
#   ВЕРНО:   scripts/gate.sh ПРИБОР args; rc=$?
#   НЕВЕРНО: scripts/gate.sh ПРИБОР args | tail -1; echo $?   # $? = код tail, не прибора
# Обертка хранит СВОЙ код, но труба ПОСЛЕ нее съедается оболочкой вызывающего —
# `exit "$rc"` тут бессилен по устройству. Нужен и вывод, и код через трубу —
# бери код из PIPESTATUS[0]:  scripts/gate.sh ПРИБОР args | cat; rc=${PIPESTATUS[0]}
#
# Новых приборов не заводит. Только обертка.
set -o pipefail

selftest() {
  local rc out
  # Себя зовем ЧЕРЕЗ ИНТЕРПРЕТАТОР, а не как исполняемый файл: копия дерева
  # (публичная вырезка, архив, распакованный zip) приходит без бита исполнения,
  # и прямой "$0" дает «Permission denied» — селфтест краснел на правах файла,
  # а не на поведении гейта. Поймано изолированным прогоном 03.09.2026.
  local SAM="bash $0"
  # прибор с кодом 7 через трубу показа -> gate дает 7
  $SAM sh -c 'echo "вывод-прибора-7"; exit 7' | cat >/dev/null; rc=${PIPESTATUS[0]}
  [ "$rc" -eq 7 ] || { echo "SELFTEST FAIL: код 7 потерян, получено $rc" >&2; return 1; }
  # прибор с кодом 0 через трубу показа -> gate дает 0
  $SAM sh -c 'echo "вывод-прибора-0"; exit 0' | cat >/dev/null; rc=${PIPESTATUS[0]}
  [ "$rc" -eq 0 ] || { echo "SELFTEST FAIL: код 0 искажен в $rc" >&2; return 1; }
  # вывод прибора виден целиком, не обрезан
  out=$($SAM sh -c 'printf "строка-1\nстрока-2\nстрока-3\n"; exit 3'); rc=$?
  [ "$rc" -eq 3 ] || { echo "SELFTEST FAIL: код 3 потерян, получено $rc" >&2; return 1; }
  case "$out" in
    *строка-1*строка-2*строка-3*) ;;
    *) echo "SELFTEST FAIL: вывод обрезан: $out" >&2; return 1;;
  esac
  # ГРАНИЦА: труба ПОСЛЕ обертки съедает ее код — это и учим вызывающего.
  # gate вернул 7, но `| tail` перебил $? своим кодом (0). Обертка бессильна.
  # Меряем в оболочке вызывающего — БЕЗ pipefail (иначе pipefail этого скрипта
  # соврет, что код 7 дошел; у реального вызова pipefail обычно нет).
  rc=$(bash -c 'set +o pipefail; bash "$0" sh -c "exit 7" | tail -1 >/dev/null; echo $?' "$0")
  if [ "$rc" -eq 7 ]; then
    echo "SELFTEST FAIL: труба после обертки не должна отдавать код прибора" >&2; return 1
  fi
  echo "gate.sh selftest: код после трубы = $rc (НЕ 7) — код обертки читать БЕЗ трубы после нее"
  echo "gate.sh selftest: OK (7->7, 0->0, вывод цел)"
}

case "$1" in
  --selftest) selftest; exit $? ;;
  "") echo "usage: scripts/gate.sh ПРИБОР [аргументы...]" >&2; exit 2 ;;
esac

# Труба показа: вывод прибора идет как есть, код — из PIPESTATUS[0], не из tee.
"$@" 2>&1 | cat
rc=${PIPESTATUS[0]}
if [ "$rc" -ne 0 ]; then
  echo "── gate: ПРИБОР ОТКАЗАЛ (код $rc) — это НЕ успех ──" >&2
fi
exit "$rc"
